import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtemp, rm, symlink, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import jwt from 'jsonwebtoken';
import { Pool } from 'pg';

const apiRoot = path.dirname(fileURLToPath(import.meta.url));
const tscBin = path.join(apiRoot, 'node_modules', '.bin', 'tsc');

/**
 * Compile the Vercel auth/me entry the way production does: TypeScript to
 * unbundled ESM, import specifiers left intact. Node then loads the JS.
 * Bundler moduleResolution is intentional — it is what hid the missing
 * `.js` extension from `tsc --noEmit` before this test existed.
 */
async function compileAuthMeEntry() {
  const outDir = await mkdtemp(path.join(tmpdir(), 'auth-me-packaging-'));
  const tsconfigPath = path.join(outDir, 'tsconfig.json');
  await writeFile(
    tsconfigPath,
    JSON.stringify({
      compilerOptions: {
        target: 'ES2022',
        module: 'ESNext',
        moduleResolution: 'bundler',
        esModuleInterop: true,
        skipLibCheck: true,
        strict: true,
        rootDir: apiRoot,
        outDir,
        noEmitOnError: true,
        declaration: false,
        sourceMap: false,
      },
      include: [
        'auth/me.ts',
        'src/auth.ts',
        'src/authService.ts',
        'src/authRepository.ts',
        'src/authDatabaseUrl.ts',
        'src/authTypes.ts',
      ].map((relative) => path.join(apiRoot, relative)),
    }),
  );
  const compiled = spawnSync(tscBin, ['-p', tsconfigPath], {
    encoding: 'utf8',
    cwd: apiRoot,
  });
  assert.equal(
    compiled.status,
    0,
    `unbundled tsc failed:\n${compiled.stdout}\n${compiled.stderr}`,
  );
  await symlink(
    path.join(apiRoot, 'node_modules'),
    path.join(outDir, 'node_modules'),
    'dir',
  );
  return outDir;
}

function createMockResponse() {
  const res = {
    statusCode: 200,
    body: undefined,
    status(code) {
      this.statusCode = code;
      return this;
    },
    json(body) {
      this.body = body;
      return this;
    },
  };
  return res;
}

test('unbundled Node ESM can load the Vercel auth/me function', async (t) => {
  const outDir = await compileAuthMeEntry();
  t.after(async () => {
    await rm(outDir, { recursive: true, force: true });
  });

  process.env.SECRET_KEY = process.env.SECRET_KEY || 'packaging-test-secret';
  process.env.DATABASE_URL =
    process.env.DATABASE_URL || 'postgresql://packaging:packaging@127.0.0.1:5432/packaging';

  const entry = path.join(outDir, 'auth', 'me.js');
  let handler;
  try {
    ({ default: handler } = await import(pathToFileURL(entry).href));
  } catch (error) {
    const code = error && typeof error === 'object' && 'code' in error ? error.code : undefined;
    assert.notEqual(
      code,
      'ERR_MODULE_NOT_FOUND',
      `Vercel Node ESM could not load auth/me imports: ${error instanceof Error ? error.message : error}`,
    );
    throw error;
  }

  await t.test('unauthenticated request returns 401 JSON', async () => {
    const res = createMockResponse();
    await handler({ headers: {} }, res);
    assert.equal(res.statusCode, 401);
    assert.deepEqual(res.body, { error: 'Missing or invalid authorization header' });
  });

  await t.test('bogus bearer token returns 401 JSON', async () => {
    const res = createMockResponse();
    await handler({ headers: { authorization: 'Bearer not-a-jwt' } }, res);
    assert.equal(res.statusCode, 401);
    assert.deepEqual(res.body, { error: 'Invalid or expired token' });
  });

  await t.test('signed-in request returns user JSON from a real Postgres path', async (st) => {
    const { buildAuthPoolConfig } = await import(
      pathToFileURL(path.join(outDir, 'src', 'authDatabaseUrl.js')).href
    );
    const setupPool = new Pool(buildAuthPoolConfig(process.env.DATABASE_URL));
    const username = `auth_me_ts_${process.pid}`;
    st.after(async () => {
      try {
        await setupPool.query('DELETE FROM users WHERE username = $1', [username]);
      } catch {
        // Schema setup may have failed before the users table existed.
      }
      await setupPool.end();
    });

    try {
      await setupPool.query('SELECT 1');
    } catch {
      if (process.env.CI === 'true') {
        assert.fail(
          'CI node-auth must reach Postgres for the signed-in auth/me path',
        );
      }
      st.skip('Postgres is not reachable in this environment');
      return;
    }

    await setupPool.query(`
      CREATE TABLE IF NOT EXISTS users (
        id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        username varchar(50) UNIQUE NOT NULL,
        email varchar(255),
        is_admin boolean NOT NULL DEFAULT false,
        password_hash varchar(255),
        password_changed_at timestamptz,
        created_at timestamptz NOT NULL DEFAULT now()
      )
    `);
    await setupPool.query(`
      CREATE TABLE IF NOT EXISTS revoked_tokens (
        id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        jti varchar(64) NOT NULL,
        revoked_at timestamptz NOT NULL DEFAULT now(),
        expires_at timestamptz NOT NULL
      )
    `);

    const inserted = await setupPool.query(
      `INSERT INTO users (username, email, is_admin, password_hash)
       VALUES ($1, $2, false, $3)
       ON CONFLICT (username) DO UPDATE
         SET email = EXCLUDED.email
       RETURNING id, username, email, is_admin`,
      [username, `${username}@example.test`, 'not-a-real-hash'],
    );
    const row = inserted.rows[0];

    const token = jwt.sign(
      { sub: username, jti: `jti-${process.pid}`, type: 'access', pc: 0 },
      process.env.SECRET_KEY,
      { algorithm: 'HS256', expiresIn: '1h' },
    );

    const started = Date.now();
    const res = createMockResponse();
    await handler({ headers: { authorization: `Bearer ${token}` } }, res);
    const elapsedMs = Date.now() - started;

    assert.equal(res.statusCode, 200);
    assert.deepEqual(res.body, {
      id: row.id,
      username: row.username,
      email: row.email,
      is_admin: row.is_admin,
    });
    assert.equal(Object.hasOwn(res.body, 'password_hash'), false);
    assert.equal(Object.hasOwn(res.body, 'password'), false);
    assert.ok(
      elapsedMs < 2000,
      `signed-in auth/me took ${elapsedMs}ms; expected well under 1s on local Postgres`,
    );
  });
});
