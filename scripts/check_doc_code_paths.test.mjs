import assert from 'node:assert/strict';
import {mkdirSync, mkdtempSync, rmSync, writeFileSync} from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {test} from 'node:test';
import {fileURLToPath} from 'node:url';

import {findStalePaths, iterMarkdownFiles} from './check_doc_code_paths.mjs';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function run(files) {
  const root = mkdtempSync(path.join(os.tmpdir(), 'doc-code-paths-'));
  try {
    for (const [name, body] of Object.entries(files)) {
      const target = path.join(root, name);
      mkdirSync(path.dirname(target), {recursive: true});
      writeFileSync(target, body, 'utf8');
    }
    return findStalePaths(root, iterMarkdownFiles(root));
  } finally {
    rmSync(root, {recursive: true, force: true});
  }
}

test('existing paths pass', () => {
  const errors = run({
    'README.md': 'See `native/lib.rs`, `native/lib.rs:12`, and `src/util.py`.\n',
    'native/lib.rs': '',
    'src/util.py': '',
  });
  assert.deepEqual(errors, []);
});

test('missing path fails with location', () => {
  const errors = run({'README.md': 'ok\nSee `app/api/gone.py` here.\n'});
  assert.deepEqual(errors, ['README.md:2: stale code path: app/api/gone.py']);
});

test('missing bare code filename fails', () => {
  assert.equal(run({'docs/a.md': 'Edit `renamed_module.py`.\n'}).length, 1);
});

test('bare filename matching any tracked basename passes', () => {
  assert.deepEqual(run({'docs/a.md': 'Edit `lib.rs`.\n', 'native/x/lib.rs': ''}), []);
});

test('sibling relative path passes', () => {
  const errors = run({
    'docs/a.md': 'See `b.md`, `sub/c.md`.\n',
    'docs/b.md': '',
    'docs/sub/c.md': '',
  });
  assert.deepEqual(errors, []);
});

test('fenced blocks, globs, placeholders and generated output are ignored', () => {
  const body =
    '```\n`app/gone.py`\n```\n' +
    'Glob `app/*.py`, template `app/<name>.py`, brace `app/{a,b}.py`, ' +
    'dated `out/db_export_YYYYMMDD.json`, build `static/react/index.html`, ' +
    'bare data `results.json`, url `https://x.test/a/b.py`.\n';
  assert.deepEqual(run({'README.md': body}), []);
});

test('ignore line marker and historical file marker', () => {
  const marked = 'Old `app/gone.py`. <!-- docs-path-check: ignore -->\nNew `app/gone2.py`.\n';
  assert.equal(run({'README.md': marked}).length, 1);
  const historical = '<!-- docs-path-check: historical -->\nOld `app/gone.py`.\n';
  assert.deepEqual(run({'README.md': historical}), []);
});

test('quoted markers do not exempt', () => {
  const body =
    'Use `<!-- docs-path-check: historical -->` or ' +
    '`<!-- docs-path-check: ignore -->` to mark history.\n' +
    'Quoted `<!-- docs-path-check: ignore -->` beside `app/gone.py`.\n';
  assert.equal(run({'README.md': body}).length, 1);
});

test('historical prefixes are skipped', () => {
  assert.deepEqual(run({'docs/issue-plans/1.md': 'Old `app/gone.py`.\n'}), []);
});

test('ignored directories are excluded from Markdown discovery', () => {
  const body = 'Old `app/gone.py`.\n';
  assert.deepEqual(
    run({'archive/a.md': body, 'node_modules/p/a.md': body, '.vercel/a.md': body}),
    [],
  );
});

test('current repository has no stale code paths', () => {
  assert.deepEqual(findStalePaths(repoRoot, iterMarkdownFiles(repoRoot)), []);
});

test('longer or mixed fences stay open until a valid closing fence', () => {
  const body =
    '````md\n```\n`app/gone.py`\n```\n`app/also_gone.py`\n````\n' +
    '~~~\n```\n`app/gone.py`\n~~~\n' +
    'After `app/real_gone.py`.\n';
  assert.deepEqual(run({'README.md': body}), ['README.md:11: stale code path: app/real_gone.py']);
});

test('fences nested in indented list items are recognized', () => {
  const body = '- item\n\n      ```\n      `app/gone.py`\n      ```\n\n- next `app/real_gone.py`\n';
  assert.deepEqual(run({'README.md': body}), ['README.md:7: stale code path: app/real_gone.py']);
});

test('route-burndown generated block is skipped', () => {
  const body =
    'before `app/real_gone.py`\n' +
    '<!-- route-burndown:begin (generated by scripts/generate_route_burndown.py, issue #4739) -->\n' +
    'inside `scripts/generate_route_burndown.py`\n' +
    '<!-- route-burndown:end -->\n' +
    'after `app/also_real_gone.py`\n';
  assert.deepEqual(run({'AGENTS.md': body}), [
    'AGENTS.md:1: stale code path: app/real_gone.py',
    'AGENTS.md:5: stale code path: app/also_real_gone.py',
  ]);
});

test('quoted route-burndown markers do not start a generated block', () => {
  const body =
    '```\n' +
    '`<!-- route-burndown:begin -->`\n' +
    '```\n' +
    'Example: `<!-- route-burndown:begin -->` in text.\n' +
    'after `app/real_gone.py`\n';
  assert.deepEqual(run({'README.md': body}), [
    'README.md:5: stale code path: app/real_gone.py',
  ]);
});
