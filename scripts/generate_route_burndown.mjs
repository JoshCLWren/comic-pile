import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {slimNativeRollRoutes} from './vercel_slim_routes.mjs';

const INVENTORY_PATH = 'docs/api/v2-route-inventory.json';
const FRAGMENT_DIR = 'docs/api/route-fragments';
const SQL_BUDGET_SOURCES_PATH = 'docs/api/sql-budget-sources.json';
const REWRITE_FRAGMENT_PATH = path.posix.join(FRAGMENT_DIR, 'vercel-rewrites.json');
const VERCEL_PATH = 'vercel.json';
const AGENTS_PATH = 'AGENTS.md';
const NATIVE_DESTINATIONS = new Set(['/api/native_roll.rs', '/api/native_issue.rs']);
const PYTHON_DESTINATION = '/api/index.py';
const VERCEL_DESTINATIONS = new Set([...NATIVE_DESTINATIONS, PYTHON_DESTINATION]);
const CATCH_ALL_SRC = '/api(?:/.*)?';
const CATCH_ALL_DEST = '/api/native_roll.rs';
const BURN_DOWN_ISSUE = 4739;
const METHOD_ORDER = ['GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'HEAD', 'OPTIONS'];
const AGENTS_BEGIN_MARKER =
  '<!-- route-burndown:begin (generated by scripts/generate_route_burndown.mjs, issue #4739) -->';
const AGENTS_END_MARKER = '<!-- route-burndown:end -->';

class BurndownGenerationError extends Error {}


function isString(value) {
  return Object.prototype.toString.call(value) === '[object String]';
}

function isBoolean(value) {
  return Object.prototype.toString.call(value) === '[object Boolean]';
}

function isObjectRecord(value) {
  return value !== null && Object.prototype.toString.call(value) === '[object Object]';
}

function loadJson(filePath) {
  const value = JSON.parse(readFileSync(filePath, 'utf8'));
  if (!isObjectRecord(value)) {
    throw new BurndownGenerationError(`${filePath} must contain a JSON object`);
  }
  return Object.fromEntries(Object.entries(value).map(([k, v]) => [String(k), v]));
}

function _object(value, context) {
  if (!isObjectRecord(value)) {
    throw new BurndownGenerationError(`${context} must be a JSON object`);
  }
  return Object.fromEntries(Object.entries(value).map(([k, v]) => [String(k), v]));
}

function _string(value, context) {
  if (!isString(value)) {
    throw new BurndownGenerationError(`${context} must be a string`);
  }
  return value;
}

function _consumers(value, context) {
  if (!Array.isArray(value) || !value.every(isString)) {
    throw new BurndownGenerationError(`${context} must be an array of strings`);
  }
  return value.filter(isString);
}

function _owner(value, context) {
  if (value === null || value === undefined) return null;
  if (!Number.isInteger(value)) {
    throw new BurndownGenerationError(`${context} must be an integer or null`);
  }
  return value;
}

function _optionalDest(value, context) {
  if (value === null || value === undefined) return null;
  if (!isString(value) || !VERCEL_DESTINATIONS.has(value)) {
    const sorted = [...VERCEL_DESTINATIONS].sort();
    throw new BurndownGenerationError(
      `${context} must be one of [${sorted.map(v => `'${v}'`).join(', ')}] or null`,
    );
  }
  return value;
}

function _optionalSrc(value, context) {
  if (value === null || value === undefined) return null;
  if (!isString(value) || value.length === 0) {
    throw new BurndownGenerationError(`${context} must be a non-empty string or null`);
  }
  return value;
}

function _optionalBool(value, context) {
  if (value === null || value === undefined) return false;
  if (!isBoolean(value)) {
    throw new BurndownGenerationError(`${context} must be a boolean`);
  }
  return value;
}

function routeRegexForPath(routePath) {
  const escapeChars = new Set(['^', '$', '.', '*', '+', '?', '(', ')', '[', ']', '{', '}', '|', '-']);
  const parts = ['^'];
  let cursor = 0;
  const re = /\{([^{}]+)\}/g;
  let match;
  while ((match = re.exec(routePath)) !== null) {
    const literal = routePath.slice(cursor, match.index);
    parts.push([...literal].map(c => (escapeChars.has(c) ? `\\${c}` : c)).join(''));
    parts.push(match[1].endsWith(':path') ? '.+' : '[^/]+');
    cursor = match.index + match[0].length;
  }
  const literal = routePath.slice(cursor);
  parts.push([...literal].map(c => (escapeChars.has(c) ? `\\${c}` : c)).join(''));
  parts.push('$');
  return parts.join('');
}

function pyFullMatch(pattern, text) {
  // Python re.fullmatch: match entire string against pattern
  const re = new RegExp(`^(?:${pattern})$`);
  return re.test(text);
}

export function _loadRouteFragments(dirPath) {
  const fragments = [];
  const seen = new Set();
  const files = readdirSync(dirPath).filter(name => name.endsWith('.json')).sort();
  for (const fileName of files) {
    if (fileName === path.posix.basename(REWRITE_FRAGMENT_PATH)) continue;
    const fragmentPath = path.posix.join(dirPath, fileName);
    const document = loadJson(fragmentPath);
    const family = _string(document.family, `${fragmentPath}.family`);
    const rawPatterns = document.owned_path_patterns;
    if (!Array.isArray(rawPatterns) || !rawPatterns.every(isString)) {
      throw new BurndownGenerationError(`${fragmentPath}.owned_path_patterns must be an array of strings`);
    }
    const defaults = _object(document.defaults ?? {}, `${fragmentPath}.defaults`);
    const rawOperations = document.operations;
    if (!Array.isArray(rawOperations) || rawOperations.length === 0) {
      throw new BurndownGenerationError(`${fragmentPath} must define a non-empty operations array`);
    }
    const operations = [];
    for (let index = 0; index < rawOperations.length; index++) {
      const operation = _object(rawOperations[index], `${fragmentPath}.operations[${index}]`);
      const bucket = _string(operation.bucket, `${fragmentPath}.operations[${index}].bucket`);
      if (!['operations', 'v1_operations', 'unversioned_operations'].includes(bucket)) {
        throw new BurndownGenerationError(`${fragmentPath} has unknown bucket '${bucket}'`);
      }
      const method = _string(operation.method, `${fragmentPath}.operations[${index}].method`);
      const routePath = _string(operation.path, `${fragmentPath}.operations[${index}].path`);
      const key = `${method}\0${routePath}`;
      if (seen.has(key)) {
        throw new BurndownGenerationError(`duplicate route fragment operation ${method} ${routePath}`);
      }
      seen.add(key);
      const merged = {...defaults, ...operation};
      delete merged.bucket;
      merged.method = method;
      merged.path = routePath;
      _optionalDest(merged.dest, `${fragmentPath}.operations[${index}].dest`);
      _optionalSrc(merged.src, `${fragmentPath}.operations[${index}].src`);
      _optionalBool(merged.exclude_from_inventory, `${fragmentPath}.operations[${index}].exclude_from_inventory`);
      operations.push({bucket, ...merged});
    }
    fragments.push({
      name: family,
      owned_path_patterns: [...rawPatterns],
      operations,
    });
  }
  return fragments;
}

function _validatedOperations(inventory) {
  const rawOperations = inventory.operations;
  if (!Array.isArray(rawOperations)) {
    throw new BurndownGenerationError('inventory must define an operations array');
  }
  const operations = [];
  for (let index = 0; index < rawOperations.length; index++) {
    const operation = _object(rawOperations[index], `operations[${index}]`);
    _string(operation.method, `operations[${index}].method`);
    _string(operation.path, `operations[${index}].path`);
    _string(operation.runtime, `operations[${index}].runtime`);
    _string(operation.status, `operations[${index}].status`);
    _owner(operation.owning_issue, `operations[${index}].owning_issue`);
    _consumers(operation.consumers, `operations[${index}].consumers`);
    operations.push(operation);
  }
  return operations;
}

function _validatedNamedOperations(value, context) {
  if (!Array.isArray(value)) {
    throw new BurndownGenerationError(`${context} must be an array`);
  }
  const operations = [];
  for (let index = 0; index < value.length; index++) {
    const operation = _object(value[index], `${context}[${index}]`);
    _string(operation.method, `${context}[${index}].method`);
    _string(operation.path, `${context}[${index}].path`);
    _string(operation.runtime, `${context}[${index}].runtime`);
    _string(operation.status, `${context}[${index}].status`);
    _owner(operation.owning_issue, `${context}[${index}].owning_issue`);
    _consumers(operation.consumers, `${context}[${index}].consumers`);
    operations.push(operation);
  }
  return operations;
}

function _mergeRouteFragments(inventory, fragments) {
  const merged = {...inventory};
  const rawOperations = _validatedOperations(inventory).filter(
    operation => operation.runtime !== 'python-fastapi',
  );
  const rawFull = _object(inventory.full_surface, 'full_surface');
  const buckets = {
    operations: rawOperations,
    v1_operations: _validatedNamedOperations(rawFull.v1_operations, 'full_surface.v1_operations'),
    unversioned_operations: _validatedNamedOperations(
      rawFull.unversioned_operations,
      'full_surface.unversioned_operations',
    ),
  };
  for (const bucket of Object.keys(buckets)) {
    buckets[bucket] = buckets[bucket].filter(operation => {
      const routePath = _string(operation.path, 'operation.path');
      for (const fragment of fragments) {
        for (const pattern of fragment.owned_path_patterns) {
          if (pyFullMatch(pattern, routePath)) return false;
        }
      }
      return true;
    });
  }
  for (const fragment of fragments) {
    for (const operation of fragment.operations) {
      const bucket = _string(operation.bucket, 'fragment.bucket');
      if (_optionalBool(operation.exclude_from_inventory, 'fragment.exclude_from_inventory')) {
        continue;
      }
      const source = {...operation};
      delete source.bucket;
      delete source.dest;
      delete source.src;
      delete source.exclude_from_inventory;
      buckets[bucket].push(source);
    }
  }
  buckets.operations.sort((a, b) => {
    if (a.path !== b.path) return a.path < b.path ? -1 : 1;
    if (a.method !== b.method) return a.method < b.method ? -1 : 1;
    return 0;
  });
  for (const bucket of ['v1_operations', 'unversioned_operations']) {
    buckets[bucket].sort((a, b) => {
      if (a.path !== b.path) return a.path < b.path ? -1 : 1;
      if (a.method !== b.method) return a.method < b.method ? -1 : 1;
      return 0;
    });
  }
  merged.operations = buckets.operations;
  merged.full_surface = {
    ...rawFull,
    v1_operations: buckets.v1_operations,
    unversioned_operations: buckets.unversioned_operations,
  };
  return merged;
}

function _resolvePreviousDestination(method, routePath, routes) {
  const concrete = routePath.replace(/\{[^}]+\}/g, '1');
  for (const route of routes) {
    if (route.src === null || route.src === undefined) continue;
    if (!pyFullMatch(route.src, concrete)) continue;
    if (route.methods && route.methods.length && !route.methods.includes(method.toUpperCase())) continue;
    return route;
  }
  return null;
}

function stableRouteSortKey(route) {
  const rawMethods = route.methods;
  let methodsStr = '';
  if (Array.isArray(rawMethods)) {
    methodsStr = rawMethods.filter(isString).join(',');
  }
  return [_string(route.src, 'route.src'), _string(route.dest, 'route.dest'), methodsStr];
}

function compareRouteKeys(a, b) {
  const ka = stableRouteSortKey(a);
  const kb = stableRouteSortKey(b);
  for (let i = 0; i < 3; i++) {
    if (ka[i] !== kb[i]) return ka[i] < kb[i] ? -1 : 1;
  }
  return 0;
}

function _fragmentVercelGroups(fragments, previousRoutes) {
  const grouped = new Map();
  for (const fragment of fragments) {
    for (const operation of fragment.operations) {
      const method = _string(operation.method, 'fragment.method');
      const routePath = _string(operation.path, 'fragment.path');
      let dest = null;
      let src = null;
      const rawDest = operation.dest;
      const rawSrc = operation.src;
      if (rawDest !== null && rawDest !== undefined) {
        dest = _optionalDest(rawDest, 'fragment.dest');
      }
      if (rawSrc !== null && rawSrc !== undefined) {
        src = _optionalSrc(rawSrc, 'fragment.src');
      }
      const previous = _resolvePreviousDestination(method, routePath, previousRoutes);
      if (dest === null) {
        if (previous === null || previous.dest === null || previous.dest === undefined) {
          throw new BurndownGenerationError(
            `${method} ${routePath} needs dest; previous vercel.json has no matching route`,
          );
        }
        dest = previous.dest;
      }
      if (src === null) {
        if (
          previous !== null &&
          previous.src !== null &&
          previous.src !== undefined &&
          previous.src !== CATCH_ALL_SRC
        ) {
          src = previous.src;
        } else {
          src = routeRegexForPath(routePath);
        }
      }
      if (!VERCEL_DESTINATIONS.has(dest)) {
        throw new BurndownGenerationError(`unknown destination '${dest}'`);
      }
      const key = `${src}\0${dest}`;
      if (!grouped.has(key)) grouped.set(key, {src, dest, methods: new Set()});
      grouped.get(key).methods.add(method.toUpperCase());
    }
  }
  const routes = [];
  for (const group of grouped.values()) {
    const effective = new Set(group.methods);
    if (group.dest === PYTHON_DESTINATION) effective.add('OPTIONS');
    const ordered = METHOD_ORDER.filter(item => effective.has(item));
    routes.push({src: group.src, methods: ordered, dest: group.dest});
  }
  const native = routes.filter(r => NATIVE_DESTINATIONS.has(r.dest)).sort(compareRouteKeys);
  const python = routes.filter(r => r.dest === PYTHON_DESTINATION).sort(compareRouteKeys);
  const ordered = [...native, ...python];
  const seen = new Set();
  for (const route of ordered) {
    const src = _string(route.src, 'route.src');
    const dest = _string(route.dest, 'route.dest');
    const routeMethods = _consumers(route.methods, 'route.methods');
    for (const method of routeMethods) {
      const identity = `${src}\0${method}`;
      if (seen.has(identity) && NATIVE_DESTINATIONS.has(dest)) {
        throw new BurndownGenerationError(`duplicate native ingress rewrite for ${method} ${src}`);
      }
      seen.add(identity);
    }
  }
  return ordered;
}

export function pythonJsonDumps(value) {
  const json = JSON.stringify(value, null, 2);
  let out = '';
  for (const ch of json) {
    const cp = ch.codePointAt(0);
    if (cp <= 0x7f) {
      out += ch;
    } else if (cp <= 0xffff) {
      out += '\\u' + cp.toString(16).padStart(4, '0');
    } else {
      const offset = cp - 0x10000;
      const hi = Math.floor(offset / 0x400) + 0xd800;
      const lo = (offset % 0x400) + 0xdc00;
      out += '\\u' + hi.toString(16).padStart(4, '0') + '\\u' + lo.toString(16).padStart(4, '0');
    }
  }
  return out + '\n';
}

function _routesFromDocument(document) {
  const rawRoutes = document.routes;
  if (!Array.isArray(rawRoutes)) {
    throw new BurndownGenerationError('vercel.json must define a routes array');
  }
  const routes = [];
  for (const rawRoute of rawRoutes) {
    if (!isObjectRecord(rawRoute)) {
      throw new BurndownGenerationError('vercel.json routes must be objects');
    }
    const full = Object.fromEntries(Object.entries(rawRoute).map(([k, v]) => [String(k), v]));
    const src = full.src;
    const dest = full.dest;
    const rawMethods = full.methods;
    let methods = [];
    if (rawMethods !== null && rawMethods !== undefined) {
      if (!Array.isArray(rawMethods) || !rawMethods.every(isString)) {
        throw new BurndownGenerationError('vercel.json route methods must be strings');
      }
      methods = rawMethods.filter(isString);
    }
    routes.push({
      src: isString(src) ? src : null,
      dest: isString(dest) ? dest : null,
      methods,
    });
  }
  return routes;
}

function _loadRoutes(filePath) {
  return _routesFromDocument(loadJson(filePath));
}

export function _generateVercelDocument(previous, fragments, {slim = true} = {}) {
  const rawRoutes = previous.routes;
  if (!Array.isArray(rawRoutes)) {
    throw new BurndownGenerationError('vercel.json must define a routes array');
  }
  const previousRoutes = [];
  const previousFull = [];
  for (const rawRoute of rawRoutes) {
    if (!isObjectRecord(rawRoute)) {
      throw new BurndownGenerationError('vercel.json routes must be objects');
    }
    const full = Object.fromEntries(Object.entries(rawRoute).map(([k, v]) => [String(k), v]));
    previousFull.push(full);
    const src = full.src;
    const dest = full.dest;
    const rawMethods = full.methods;
    let methods = [];
    if (rawMethods !== null && rawMethods !== undefined) {
      if (!Array.isArray(rawMethods) || !rawMethods.every(isString)) {
        throw new BurndownGenerationError('vercel.json route methods must be strings');
      }
      methods = rawMethods.filter(isString);
    }
    previousRoutes.push({
      src: isString(src) ? src : null,
      dest: isString(dest) ? dest : null,
      methods,
    });
  }
  const fragmentRoutes = _fragmentVercelGroups(fragments, previousRoutes);
  const fragmentSrcs = new Set(fragmentRoutes.map(r => String(r.src)));
  const baselineNatives = [];
  const baselinePythons = [];
  const nonApi = [];
  let catchAll = null;
  for (const route of previousFull) {
    const src = route.src;
    const dest = route.dest;
    if (src === CATCH_ALL_SRC) {
      catchAll = route;
      continue;
    }
    if (NATIVE_DESTINATIONS.has(dest)) {
      if (fragmentSrcs.has(src)) continue;
      baselineNatives.push(route);
    } else if (dest === PYTHON_DESTINATION) {
      if (fragmentSrcs.has(src)) continue;
      baselinePythons.push(route);
    } else {
      nonApi.push(Object.fromEntries(Object.entries(route).map(([k, v]) => [String(k), v])));
    }
  }
  if (catchAll === null || catchAll.dest !== CATCH_ALL_DEST) {
    throw new BurndownGenerationError('catch-all route missing from vercel.json');
  }
  const nativeFragment = fragmentRoutes.filter(r => NATIVE_DESTINATIONS.has(r.dest));
  const pythonFragment = fragmentRoutes.filter(r => r.dest === PYTHON_DESTINATION);
  const generated = [...nativeFragment, ...pythonFragment].map(r => ({
    src: r.src,
    methods: r.methods,
    dest: r.dest,
  }));
  const fullRoutes = [
    ...baselineNatives,
    ...generated,
    ...baselinePythons,
    catchAll,
    ...nonApi,
  ];
  const newRoutes = slim
    ? slimNativeRollRoutes(
      fullRoutes,
      new Set(generated),
    )
    : fullRoutes;
  const nativeIndices = [];
  const pythonIndices = [];
  let catchIndex = -1;
  for (let index = 0; index < newRoutes.length; index++) {
    const route = newRoutes[index];
    if (NATIVE_DESTINATIONS.has(route.dest) && route.src !== CATCH_ALL_SRC) nativeIndices.push(index);
    if (route.dest === PYTHON_DESTINATION) pythonIndices.push(index);
    if (route.src === CATCH_ALL_SRC) catchIndex = index;
  }
  if (nativeIndices.length && pythonIndices.length && Math.max(...nativeIndices) > Math.min(...pythonIndices)) {
    throw new BurndownGenerationError('native routes must precede Python exceptions');
  }
  if (pythonIndices.length && catchIndex < Math.max(...pythonIndices)) {
    throw new BurndownGenerationError('Python exceptions must precede catch-all');
  }
  const document = Object.fromEntries(Object.entries(previous).map(([k, v]) => [String(k), v]));
  document.routes = newRoutes;
  return document;
}

function _renderVercelText(document) {
  return pythonJsonDumps(document);
}

function _resolveDestination(method, routePath, routes) {
  const concrete = routePath.replace(/\{[^}]+\}/g, '1');
  for (const route of routes) {
    if (route.src === null || route.src === undefined) continue;
    if (!pyFullMatch(route.src, concrete)) continue;
    if (route.methods && route.methods.length && !route.methods.includes(method.toUpperCase())) continue;
    return route.dest;
  }
  return null;
}

function _classifyBurndown(runtime, consumers, destination) {
  if (runtime === 'native-rust') {
    if (!NATIVE_DESTINATIONS.has(destination)) {
      throw new BurndownGenerationError(`native-rust operation routes to non-native '${destination}'`);
    }
    return 'native Rust';
  }
  if (runtime === 'python-fastapi') {
    if (NATIVE_DESTINATIONS.has(destination)) {
      return 'shadowed by Rust';
    }
    if (consumers.length) {
      return 'live transitional Python with callers';
    }
    return 'unreferenced/orphaned';
  }
  throw new BurndownGenerationError(`unknown runtime '${runtime}'`);
}

function _enrichOperations(operations, routes) {
  const enriched = [];
  for (const operation of operations) {
    const method = _string(operation.method, 'method');
    const routePath = _string(operation.path, 'path');
    const runtime = _string(operation.runtime, 'runtime');
    const consumers = _consumers(operation.consumers, 'consumers');
    const destination = _resolveDestination(method, routePath, routes);
    if (destination === null || destination === undefined) {
      throw new BurndownGenerationError(`${method} ${routePath} has no vercel.json route`);
    }
    const status = _classifyBurndown(runtime, consumers, destination);
    enriched.push({
      ...operation,
      ingress_destination: destination,
      burndown_status: status,
      verified_against: 'vercel.json',
    });
  }
  return enriched;
}

function _burndownSummary(enriched) {
  const _count = status => enriched.filter(item => item.burndown_status === status).length;
  const total = enriched.length;
  const native = enriched.filter(item => item.runtime === 'native-rust').length;
  const pythonTotal = total - native;
  return {
    generated_by: 'scripts/generate_route_burndown.mjs',
    issue: BURN_DOWN_ISSUE,
    ingress_source: 'vercel.json',
    total_live_operations: total,
    native_rust: native,
    python_fastapi: pythonTotal,
    native_rust_status: _count('native Rust'),
    shadowed_by_rust: _count('shadowed by Rust'),
    live_transitional_python_with_callers: _count('live transitional Python with callers'),
    unreferenced_or_orphaned: _count('unreferenced/orphaned'),
  };
}

function _enrichNamedOperations(operations, routes, context) {
  const enriched = [];
  for (const operation of operations) {
    const method = _string(operation.method, `${context}.method`);
    const routePath = _string(operation.path, `${context}.path`);
    const runtime = _string(operation.runtime, `${context}.runtime`);
    const consumers = _consumers(operation.consumers, `${context}.consumers`);
    const destination = _resolveDestination(method, routePath, routes);
    if (destination === null || destination === undefined) {
      throw new BurndownGenerationError(`${method} ${routePath} has no vercel.json route`);
    }
    const status = _classifyBurndown(runtime, consumers, destination);
    enriched.push({
      ...operation,
      ingress_destination: destination,
      burndown_status: status,
      verified_against: 'vercel.json',
    });
  }
  return enriched;
}

function _countStatus(operations, status) {
  return operations.filter(item => item.burndown_status === status).length;
}

function _validatedFullSurface(inventory) {
  const full = _object(inventory.full_surface, 'full_surface');
  const catchAll = _object(full.catch_all, 'full_surface.catch_all');
  catchAll.dest = CATCH_ALL_DEST;
  _string(catchAll.src, 'full_surface.catch_all.src');
  _string(catchAll.dest, 'full_surface.catch_all.dest');
  return catchAll;
}

function _verifyFullSurfaceEntries(catchAll, routes) {
  const src = _string(catchAll.src, 'catch_all.src');
  const dest = _string(catchAll.dest, 'catch_all.dest');
  if (src !== CATCH_ALL_SRC || dest !== CATCH_ALL_DEST) {
    throw new BurndownGenerationError(`catch-all must be '${CATCH_ALL_SRC}' -> '${CATCH_ALL_DEST}'`);
  }
  if (!routes.some(route => route.src === CATCH_ALL_SRC && route.dest === CATCH_ALL_DEST)) {
    throw new BurndownGenerationError('catch-all route missing from vercel.json');
  }
}

function _fullSurfaceSummary(v1Operations, unversionedOperations, catchAll) {
  const v1Total = v1Operations.length;
  const unversionedTotal = unversionedOperations.length;
  const v1Shadowed = _countStatus(v1Operations, 'shadowed by Rust');
  const unversionedShadowed = _countStatus(unversionedOperations, 'shadowed by Rust');
  const v1Live = _countStatus(v1Operations, 'live transitional Python with callers');
  const unversionedLive = _countStatus(unversionedOperations, 'live transitional Python with callers');
  const v1Orphaned = _countStatus(v1Operations, 'unreferenced/orphaned');
  const unversionedOrphaned = _countStatus(unversionedOperations, 'unreferenced/orphaned');
  return {
    generated_by: 'scripts/generate_route_burndown.mjs',
    issue: BURN_DOWN_ISSUE,
    ingress_source: 'vercel.json',
    catch_all_src: _string(catchAll.src, 'catch_all.src'),
    catch_all_dest: _string(catchAll.dest, 'catch_all.dest'),
    v1_total: v1Total,
    v1_shadowed_by_rust: v1Shadowed,
    v1_live_python: v1Live,
    v1_orphaned: v1Orphaned,
    unversioned_total: unversionedTotal,
    unversioned_shadowed_by_rust: unversionedShadowed,
    unversioned_live_python: unversionedLive,
    unversioned_orphaned: unversionedOrphaned,
    total_python_surface: v1Total + unversionedTotal,
    total_shadowed_by_rust: v1Shadowed + unversionedShadowed,
    total_live_python: v1Live + unversionedLive,
    total_orphaned: v1Orphaned + unversionedOrphaned,
  };
}

function _renderFullSurface(inventory, routes, v2Operations) {
  const catchAll = _validatedFullSurface(inventory);
  _verifyFullSurfaceEntries(catchAll, routes);
  const rawFull = inventory.full_surface;
  const rawFullMap = Object.fromEntries(Object.entries(rawFull).map(([k, v]) => [String(k), v]));
  const v1Raw = _validatedNamedOperations(rawFullMap.v1_operations, 'full_surface.v1_operations');
  const unversionedRaw = _validatedNamedOperations(
    rawFullMap.unversioned_operations,
    'full_surface.unversioned_operations',
  );
  const v1Operations = _enrichNamedOperations(v1Raw, routes, 'full_surface.v1_operations');
  const unversionedOperations = _enrichNamedOperations(
    unversionedRaw,
    routes,
    'full_surface.unversioned_operations',
  );
  const summary = _fullSurfaceSummary(v1Operations, unversionedOperations, catchAll);
  return {
    generated_by: 'scripts/generate_route_burndown.mjs',
    issue: BURN_DOWN_ISSUE,
    ingress_source: 'vercel.json',
    summary,
    catch_all: {...catchAll},
    v1_operations: v1Operations,
    unversioned_operations: unversionedOperations,
  };
}

function _renderInventory(inventory, routes, fragments) {
  const sourceInventory = _mergeRouteFragments(inventory, fragments);
  const budgetSources = loadJson(SQL_BUDGET_SOURCES_PATH);
  const budgetEntries = budgetSources.operations;
  if (!Array.isArray(budgetEntries)) {
    throw new BurndownGenerationError('SQL budget sources must contain operations');
  }
  const sourceOperations = _validatedOperations(sourceInventory);
  const operationMap = new Map(sourceOperations.map(operation => [`${operation.method}\0${operation.path}`, operation]));
  const seenBudgets = new Set();
  for (let index = 0; index < budgetEntries.length; index++) {
    const entry = _object(budgetEntries[index], `sql-budget-sources.operations[${index}]`);
    const method = _string(entry.method, 'sql budget method');
    const routePath = _string(entry.path, 'sql budget path');
    const key = `${method}\0${routePath}`;
    if (seenBudgets.has(key) || !operationMap.has(key)) {
      throw new BurndownGenerationError(`duplicate or unknown SQL budget operation (${method}, ${routePath})`);
    }
    seenBudgets.add(key);
    const budget = _object(entry.sql_budget, `sql budget (${method}, ${routePath})`);
    const op = operationMap.get(key);
    op.sql_budget = budget;
    if (Object.prototype.hasOwnProperty.call(entry, 'db_free')) {
      op.db_free = _optionalBool(entry.db_free, 'db_free');
    }
  }
  sourceInventory.operations = sourceOperations;
  const operations = _enrichOperations(sourceOperations, routes);
  const summary = _burndownSummary(operations);
  const schemaVersion = Object.prototype.hasOwnProperty.call(sourceInventory, 'schema_version')
    ? sourceInventory.schema_version
    : 1;
  const description = Object.prototype.hasOwnProperty.call(sourceInventory, 'description')
    ? sourceInventory.description
    : '';
  const retired = Object.prototype.hasOwnProperty.call(sourceInventory, 'retired_legacy_operations')
    ? sourceInventory.retired_legacy_operations
    : [];
  const fullSurface = _renderFullSurface(sourceInventory, routes, operations);
  const payload = {
    schema_version: schemaVersion,
    description,
    updated_by_issue: BURN_DOWN_ISSUE,
    burndown: summary,
    operations,
    full_surface: fullSurface,
    retired_legacy_operations: retired,
  };
  const text = pythonJsonDumps(payload);
  return [payload, text];
}

function _operationOneLiner(operation) {
  const method = _string(operation.method, 'method');
  const routePath = _string(operation.path, 'path');
  const runtime = _string(operation.runtime, 'runtime');
  return `\`${method} ${routePath} -> ${runtime}\``;
}

function _groupByOwner(enriched) {
  const groups = new Map();
  for (const operation of enriched) {
    const owner = _owner(operation.owning_issue, 'owning_issue');
    const key = owner === null ? 'null' : String(owner);
    if (!groups.has(key)) groups.set(key, {owner, operations: []});
    groups.get(key).operations.push(operation);
  }
  const orderedKeys = [...groups.keys()].sort((a, b) => {
    const ao = groups.get(a).owner;
    const bo = groups.get(b).owner;
    const aNull = ao === null ? 1 : 0;
    const bNull = bo === null ? 1 : 0;
    if (aNull !== bNull) return aNull - bNull;
    if (ao !== bo) return ao - bo;
    return 0;
  });
  const result = [];
  for (const key of orderedKeys) {
    const group = groups.get(key);
    const operations = [...group.operations].sort((a, b) => {
      const ap = _string(a.path, 'path');
      const bp = _string(b.path, 'path');
      if (ap !== bp) return ap < bp ? -1 : 1;
      const am = _string(a.method, 'method');
      const bm = _string(b.method, 'method');
      if (am !== bm) return am < bm ? -1 : 1;
      return 0;
    });
    result.push([group.owner, operations]);
  }
  return result;
}

function _renderAgentsBlock(enriched, fullSummary = null) {
  const summary = _burndownSummary(enriched);
  const total = summary.total_live_operations;
  const native = summary.native_rust;
  const pythonTotal = summary.python_fastapi;
  const sortedOperations = [...enriched].sort((a, b) => {
    const ap = _string(a.path, 'path');
    const bp = _string(b.path, 'path');
    if (ap !== bp) return ap < bp ? -1 : 1;
    const am = _string(a.method, 'method');
    const bm = _string(b.method, 'method');
    if (am !== bm) return am < bm ? -1 : 1;
    return 0;
  });
  const pythonOps = sortedOperations.filter(item => item.runtime === 'python-fastapi');
  const orphanOps = pythonOps.filter(item => item.burndown_status === 'unreferenced/orphaned');
  const transitionalOps = pythonOps.filter(item => item.burndown_status !== 'unreferenced/orphaned');
  const lines = [
    AGENTS_BEGIN_MARKER,
    '',
    '## Current deployed v2 runtime (generated from `vercel.json`)',
    '',
    '> Generated by `scripts/generate_route_burndown.mjs` (issue #4739).',
    '> Do not hand-edit; run `node scripts/generate_route_burndown.mjs`',
    '> after changing `vercel.json`, route fragments, or the inventory.',
    '> API version is not implementation language.',
    '',
    `- Live v2 operations: ${total} (${native} native-rust + ${pythonTotal} python-fastapi).`,
    '- Native ingress: `/api/native_roll.rs`, `/api/native_issue.rs` (via `vercel.json`).',
  ];
  if (fullSummary !== null) {
    const v1Total = fullSummary.v1_total;
    const v1Shadowed = fullSummary.v1_shadowed_by_rust;
    const v1Live = fullSummary.v1_live_python;
    const unversionedTotal = fullSummary.unversioned_total;
    const unversionedShadowed = fullSummary.unversioned_shadowed_by_rust;
    const unversionedLive = fullSummary.unversioned_live_python;
    const pythonSurface = fullSummary.total_python_surface;
    lines.push(
      `- Full Python-handler surface: ${pythonSurface} operations ` +
      `(v1 ${v1Total} + unversioned ${unversionedTotal}); ` +
      `v1 active ${v1Live} live Python / ${v1Shadowed} migrated ` +
      '(shadowed by Rust); unversioned active ' +
      `${unversionedLive} live Python / ${unversionedShadowed} migrated ` +
      '(shadowed by Rust); remaining declared methods use explicit Python exceptions.',
    );
    lines.push('- Catch-all: `/api(?:/.*)? -> /api/native_roll.rs` (Rust JSON 404).');
    lines.push(
      '- Full-surface inventory (v2 + v1 + unversioned + catch-all) and per-operation callers: see `docs/api/v2-route-inventory.json` `full_surface` (authoritative).',
    );
  }
  for (const item of orphanOps) {
    const method = _string(item.method, 'method');
    const routePath = _string(item.path, 'path');
    const destination = _string(item.ingress_destination, 'ingress_destination');
    const owner = _owner(item.owning_issue, 'owning_issue');
    const ownerText = owner !== null ? `#${owner}` : 'none';
    lines.push(
      `- Python orphan: \`${method} ${routePath} -> python-fastapi\` via \`${destination}\` (owner ${ownerText}, no callers).`,
    );
  }
  for (const item of transitionalOps) {
    const method = _string(item.method, 'method');
    const routePath = _string(item.path, 'path');
    const runtime = _string(item.runtime, 'runtime');
    const destination = _string(item.ingress_destination, 'ingress_destination');
    const owner = _owner(item.owning_issue, 'owning_issue');
    const ownerText = owner !== null ? `#${owner}` : 'none';
    lines.push(
      `- Python transitional: \`${method} ${routePath} -> ${runtime}\` via \`${destination}\` (owner ${ownerText}).`,
    );
  }
  lines.push(
    '- Full caller lists and ingress destinations: see `docs/api/v2-route-inventory.json` (authoritative).',
    '',
    'Deployed runtime by cutover owner (`METHOD path -> runtime`):',
    '',
  );
  for (const [owner, operations] of _groupByOwner(enriched)) {
    const ownerText = owner !== null ? `#${owner}` : 'none';
    const oneLiners = operations.map(item => _operationOneLiner(item)).join('; ');
    lines.push(`- ${ownerText} (${operations.length}): ${oneLiners}`);
  }
  lines.push(AGENTS_END_MARKER);
  return lines.join('\n');
}

function _renderAgentsText(original, block) {
  const beginIndex = original.indexOf('<!-- route-burndown:begin');
  const endIndex = original.indexOf(AGENTS_END_MARKER);
  if (beginIndex !== -1 && endIndex !== -1 && beginIndex < endIndex) {
    return original.slice(0, beginIndex) + block + original.slice(endIndex + AGENTS_END_MARKER.length);
  }
  const anchor = '## MANDATORY: Frontend Visual Policy';
  const anchorIndex = original.indexOf(anchor);
  if (anchorIndex !== -1) {
    const before = original.slice(0, anchorIndex).replace(/\s+$/, '');
    const after = original.slice(anchorIndex);
    return before + '\n\n' + block + '\n\n' + after;
  }
  return original.replace(/\s+$/, '') + '\n\n' + block + '\n';
}

function _renderRewriteFragment(fragments, routes) {
  const paths = new Set();
  for (const fragment of fragments) {
    for (const operation of fragment.operations) {
      paths.add(_string(operation.path, 'fragment.path'));
    }
  }
  const selected = [];
  for (let index = 0; index < routes.length; index++) {
    const route = routes[index];
    if (
      route.src === null ||
      route.src === CATCH_ALL_SRC ||
      ![...NATIVE_DESTINATIONS, '/api/index.py'].includes(route.dest)
    ) {
      continue;
    }
    let matches = false;
    for (const routePath of paths) {
      const concrete = routePath.replace(/\{[^}]+\}/g, '1');
      if (pyFullMatch(route.src, concrete)) {
        matches = true;
        break;
      }
    }
    if (matches) selected.push([index, route]);
  }
  const native = selected.flatMap(([, route]) => (NATIVE_DESTINATIONS.has(route.dest) ? [route] : []));
  const python = selected.flatMap(([, route]) => (route.dest === '/api/index.py' ? [route] : []));
  const ordered = [...native, ...python];
  const payload = {
    generated_by: 'scripts/generate_route_burndown.mjs',
    source_fragments: fragments.map(fragment => fragment.name),
    routes: ordered.map(route => ({src: route.src, methods: [...route.methods], dest: route.dest})),
  };
  return pythonJsonDumps(payload);
}

function _parseArgs(argv) {
  const args = {
    inventory: INVENTORY_PATH,
    fragments: FRAGMENT_DIR,
    'rewrite-fragment': REWRITE_FRAGMENT_PATH,
    vercel: VERCEL_PATH,
    agents: AGENTS_PATH,
    check: false,
  };
  for (let i = 2; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--check') {
      args.check = true;
    } else if (arg === '--inventory') {
      args.inventory = argv[++i];
    } else if (arg === '--fragments') {
      args.fragments = argv[++i];
    } else if (arg === '--rewrite-fragment') {
      args['rewrite-fragment'] = argv[++i];
    } else if (arg === '--vercel') {
      args.vercel = argv[++i];
    } else if (arg === '--agents') {
      args.agents = argv[++i];
    } else if (arg === '--help' || arg === '-h') {
      console.log('usage: generate_route_burndown.mjs [--inventory PATH] [--fragments DIR] [--rewrite-fragment PATH] [--vercel PATH] [--agents PATH] [--check]');
      process.exit(0);
    } else {
      throw new BurndownGenerationError(`unknown argument: ${arg}`);
    }
  }
  return args;
}

export function main(argv = process.argv) {
  let args;
  try {
    args = _parseArgs(argv);
  } catch (exc) {
    if (exc instanceof BurndownGenerationError) {
      console.log(`burndown generation failed: ${exc.message}`);
      return 2;
    }
    throw exc;
  }
  try {
    const inventory = loadJson(args.inventory);
    const fragments = _loadRouteFragments(args.fragments);
    const previousVercel = loadJson(args.vercel);
    const vercelDocument = _generateVercelDocument(previousVercel, fragments);
    const vercelText = _renderVercelText(vercelDocument);
    const routes = _routesFromDocument(vercelDocument);
    const [payload, inventoryText] = _renderInventory(inventory, routes, fragments);
    const mergedInventory = _mergeRouteFragments(inventory, fragments);
    const enrichedOperations = _enrichOperations(_validatedOperations(mergedInventory), routes);
    const rewriteText = _renderRewriteFragment(fragments, routes);
    const fullSurface = payload.full_surface;
    let fullSummary = null;
    if (isObjectRecord(fullSurface)) {
      const rawSummary = fullSurface.summary;
      if (isObjectRecord(rawSummary)) {
        fullSummary = Object.fromEntries(Object.entries(rawSummary).map(([k, v]) => [String(k), v]));
      }
    }
    const block = _renderAgentsBlock(enrichedOperations, fullSummary);
    const agentsOriginal = readFileSync(args.agents, 'utf8');
    const agentsText = _renderAgentsText(agentsOriginal, block);

    if (args.check) {
      const inventoryCurrent = readFileSync(args.inventory, 'utf8');
      const vercelCurrent = readFileSync(args.vercel, 'utf8');
      const agentsCurrent = readFileSync(args.agents, 'utf8');
      const rewriteCurrent = readFileSync(args['rewrite-fragment'], 'utf8');
      if (
        inventoryCurrent !== inventoryText ||
        vercelCurrent !== vercelText ||
        agentsCurrent !== agentsText ||
        rewriteCurrent !== rewriteText
      ) {
        console.log(
          'Route burndown is stale; run `node scripts/generate_route_burndown.mjs` and commit the result.',
        );
        return 1;
      }
      console.log(
        `Verified route burndown: ${args.inventory}, ${args.vercel}, ${args.agents}, and ${args['rewrite-fragment']}`,
      );
      return 0;
    }

    writeFileSync(args.inventory, inventoryText, 'utf8');
    writeFileSync(args.vercel, vercelText, 'utf8');
    writeFileSync(args.agents, agentsText, 'utf8');
    writeFileSync(args['rewrite-fragment'], rewriteText, 'utf8');
    console.log(
      `Wrote route burndown: ${args.inventory}, ${args.vercel}, ${args.agents}, and ${args['rewrite-fragment']}`,
    );
    return 0;
  } catch (exc) {
    if (exc instanceof BurndownGenerationError) {
      console.log(`burndown generation failed: ${exc.message}`);
      return 2;
    }
    throw exc;
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exit(main());
}
