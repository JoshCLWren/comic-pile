#!/usr/bin/env python3
"""Regenerate the v2 route burndown from family route fragments.

The burndown is derived from checked-in sources only:

* ``docs/api/route-fragments/*.json`` declares family-owned route metadata
  (``creators``, ``dependencies``, plus one file per browser-called family
  with an open migration slice); the generator merges those fragments into
  the generated inventory view and derives ingress from each operation's
  explicit ``dest``/``src`` so a family slice only edits its own fragment
  plus the Rust handler/tests,
* ``docs/api/v2-route-inventory.json`` declares every live ``/api/v2``
  operation plus the full Python-handler surface (``v1`` and unversioned
  operations, the catch-all ingress, and the orphan
  ``GET /api/v2/reading-boundaries/{thread_id}``), each with its runtime,
  status, known callers, and cutover owner, and
* ``vercel.json`` preserves the non-API baseline (static, docs, SPA,
  crons); its API routes are regenerated from fragments plus that
  baseline in deterministic native-before-Python order, and
  ``docs/api/route-fragments/vercel-rewrites.json`` is a generated
  family-scoped rewrite artifact with native routes first.

For each operation this generator resolves the first matching Vercel route
against the regenerated ingress, classifies the burndown status (native
Rust, shadowed by Rust, live transitional Python with callers, or
unreferenced/orphaned), and writes the result back into the inventory as
deterministic ``burndown`` fields plus a compact runtime summary in
``AGENTS.md``. Hidden cron exceptions (for example
``GET /api/v1/cron/release-sync``) are preserved as explicit Python
fragment or baseline routes. Run without arguments to regenerate, or with
``--check`` to fail when any checked-in file is stale. API version is not
implementation language: the URL segment never implies the runtime.
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
import json
from pathlib import Path
import re
from typing import Final

INVENTORY_PATH: Final = Path("docs/api/v2-route-inventory.json")
FRAGMENT_DIR: Final = Path("docs/api/route-fragments")
REWRITE_FRAGMENT_PATH: Final = FRAGMENT_DIR / "vercel-rewrites.json"
VERCEL_PATH: Final = Path("vercel.json")
AGENTS_PATH: Final = Path("AGENTS.md")
NATIVE_DESTINATIONS: Final = frozenset({"/api/native_roll.rs", "/api/native_issue.rs"})
PYTHON_DESTINATION: Final = "/api/index.py"
VERCEL_DESTINATIONS: Final = NATIVE_DESTINATIONS | {PYTHON_DESTINATION}
CATCH_ALL_SRC: Final = "/api(?:/.*)?"
CATCH_ALL_DEST: Final = "/api/native_roll.rs"
ORPHAN_METHOD: Final = "GET"
ORPHAN_PATH: Final = "/api/v2/reading-boundaries/{thread_id}"
BURN_DOWN_ISSUE: Final = 4739
METHOD_ORDER: Final = ("GET", "POST", "PUT", "PATCH", "DELETE", "HEAD", "OPTIONS")
AGENTS_BEGIN_MARKER: Final = (
    "<!-- route-burndown:begin "
    "(generated by scripts/generate_route_burndown.py, issue #4739) -->"
)
AGENTS_END_MARKER: Final = "<!-- route-burndown:end -->"


class BurndownGenerationError(ValueError):
    """Raised when the inventory and ingress disagree."""


@dataclass(frozen=True)
class VercelRoute:
    """One validated entry from the ``routes`` array in ``vercel.json``."""

    src: str | None
    dest: str | None
    methods: tuple[str, ...]


@dataclass(frozen=True)
class RouteFragment:
    """One family-owned source fragment and its route metadata."""

    name: str
    owned_path_patterns: tuple[str, ...]
    operations: tuple[dict[str, object], ...]


def load_json(path: Path) -> dict[str, object]:
    """Load a JSON object from ``path``.

    Args:
        path: JSON file to load.

    Returns:
        A string-keyed object mapping.

    Raises:
        BurndownGenerationError: When the file does not contain a JSON object.
    """
    value: object = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise BurndownGenerationError(f"{path} must contain a JSON object")
    return {str(key): item for key, item in value.items()}


def _object(value: object, context: str) -> dict[str, object]:
    """Narrow ``value`` to a string-keyed JSON object.

    Args:
        value: Value to narrow.
        context: Human-readable context for error messages.

    Returns:
        A string-keyed object mapping.

    Raises:
        BurndownGenerationError: When ``value`` is not a JSON object.
    """
    if not isinstance(value, dict):
        raise BurndownGenerationError(f"{context} must be a JSON object")
    return {str(key): item for key, item in value.items()}


def _string(value: object, context: str) -> str:
    """Narrow ``value`` to a string.

    Args:
        value: Value to narrow.
        context: Human-readable context for error messages.

    Returns:
        The string value.

    Raises:
        BurndownGenerationError: When ``value`` is not a string.
    """
    if not isinstance(value, str):
        raise BurndownGenerationError(f"{context} must be a string")
    return value


def _consumers(value: object, context: str) -> list[str]:
    """Narrow ``value`` to a list of caller paths.

    Args:
        value: Value to narrow.
        context: Human-readable context for error messages.

    Returns:
        The caller path list.

    Raises:
        BurndownGenerationError: When ``value`` is not a list of strings.
    """
    if not isinstance(value, list) or not all(isinstance(item, str) for item in value):
        raise BurndownGenerationError(f"{context} must be an array of strings")
    return [item for item in value if isinstance(item, str)]


def _owner(value: object, context: str) -> int | None:
    """Narrow ``value`` to an owning issue number or ``None``.

    Args:
        value: Value to narrow.
        context: Human-readable context for error messages.

    Returns:
        The owning issue number, if any.

    Raises:
        BurndownGenerationError: When ``value`` is neither int nor ``None``.
    """
    if value is None:
        return None
    if not isinstance(value, int):
        raise BurndownGenerationError(f"{context} must be an integer or null")
    return value


def _optional_dest(value: object, context: str) -> str | None:
    """Narrow ``value`` to a Vercel destination or ``None`` when absent.

    Args:
        value: Value to narrow.
        context: Human-readable context for error messages.

    Returns:
        The destination string, if any.

    Raises:
        BurndownGenerationError: When ``value`` is not a known destination.
    """
    if value is None:
        return None
    if not isinstance(value, str) or value not in VERCEL_DESTINATIONS:
        raise BurndownGenerationError(
            f"{context} must be one of {sorted(VERCEL_DESTINATIONS)} or null"
        )
    return value


def _optional_src(value: object, context: str) -> str | None:
    """Narrow ``value`` to a Vercel source pattern or ``None`` when absent.

    Args:
        value: Value to narrow.
        context: Human-readable context for error messages.

    Returns:
        The source pattern string, if any.

    Raises:
        BurndownGenerationError: When ``value`` is not a string.
    """
    if value is None:
        return None
    if not isinstance(value, str) or not value:
        raise BurndownGenerationError(f"{context} must be a non-empty string or null")
    return value


def _optional_bool(value: object, context: str) -> bool:
    """Narrow ``value`` to a boolean, defaulting to ``False`` when absent.

    Args:
        value: Value to narrow.
        context: Human-readable context for error messages.

    Returns:
        The boolean value.

    Raises:
        BurndownGenerationError: When ``value`` is not a boolean.
    """
    if value is None:
        return False
    if not isinstance(value, bool):
        raise BurndownGenerationError(f"{context} must be a boolean")
    return value


def route_regex_for_path(path: str) -> str:
    """Build the canonical Vercel regex for one inventory path template.

    Mirrors ``routeRegex`` in ``scripts/generate_vercel_routes.mjs`` so
    Python and Node derive identical ``src`` strings for new operations.

    Args:
        path: Inventory path template such as ``/api/v1/tags/{tag_id}/``.

    Returns:
        The anchored regex source string.
    """
    escape_chars = set("^$.*+?()[]{}|-")
    parts: list[str] = ["^"]
    cursor = 0
    for match in re.finditer(r"\{([^{}]+)\}", path):
        literal = path[cursor : match.index()]
        parts.append("".join(f"\\{c}" if c in escape_chars else c for c in literal))
        parts.append(".+" if match.group(1).endswith(":path") else "[^/]+")
        cursor = match.index() + len(match.group(0))
    literal = path[cursor:]
    parts.append("".join(f"\\{c}" if c in escape_chars else c for c in literal))
    parts.append("$")
    return "".join(parts)


def _load_route_fragments(path: Path) -> list[RouteFragment]:
    """Load family-owned route metadata in deterministic filename order.

    Args:
        path: Directory containing family JSON fragments.

    Returns:
        Validated route fragments.

    Raises:
        BurndownGenerationError: When a fragment is malformed or duplicates an
            operation already declared by another fragment.
    """
    fragments: list[RouteFragment] = []
    seen: set[tuple[str, str]] = set()
    for fragment_path in sorted(path.glob("*.json")):
        if fragment_path.name == REWRITE_FRAGMENT_PATH.name:
            continue
        document = load_json(fragment_path)
        family = _string(document.get("family"), f"{fragment_path}.family")
        raw_patterns = document.get("owned_path_patterns")
        if not isinstance(raw_patterns, list) or not all(
            isinstance(pattern, str) for pattern in raw_patterns
        ):
            raise BurndownGenerationError(
                f"{fragment_path}.owned_path_patterns must be an array of strings"
            )
        defaults = _object(document.get("defaults", {}), f"{fragment_path}.defaults")
        raw_operations = document.get("operations")
        if not isinstance(raw_operations, list) or not raw_operations:
            raise BurndownGenerationError(
                f"{fragment_path} must define a non-empty operations array"
            )
        operations: list[dict[str, object]] = []
        for index, raw_operation in enumerate(raw_operations):
            operation = _object(raw_operation, f"{fragment_path}.operations[{index}]")
            bucket = _string(
                operation.get("bucket"),
                f"{fragment_path}.operations[{index}].bucket",
            )
            if bucket not in {"operations", "v1_operations", "unversioned_operations"}:
                raise BurndownGenerationError(f"{fragment_path} has unknown bucket {bucket!r}")
            method = _string(operation.get("method"), f"{fragment_path}.operations[{index}].method")
            route_path = _string(operation.get("path"), f"{fragment_path}.operations[{index}].path")
            key = (method, route_path)
            if key in seen:
                raise BurndownGenerationError(
                    f"duplicate route fragment operation {method} {route_path}"
                )
            seen.add(key)
            merged = dict(defaults)
            merged.update(operation)
            merged.pop("bucket", None)
            merged["method"] = method
            merged["path"] = route_path
            _optional_dest(
                merged.get("dest"), f"{fragment_path}.operations[{index}].dest"
            )
            _optional_src(
                merged.get("src"), f"{fragment_path}.operations[{index}].src"
            )
            _optional_bool(
                merged.get("exclude_from_inventory"),
                f"{fragment_path}.operations[{index}].exclude_from_inventory",
            )
            operations.append({"bucket": bucket, **merged})
        fragments.append(
            RouteFragment(
                name=family,
                owned_path_patterns=tuple(raw_patterns),
                operations=tuple(operations),
            )
        )
    return fragments


def _merge_route_fragments(
    inventory: dict[str, object],
    fragments: list[RouteFragment],
) -> dict[str, object]:
    """Merge family fragments into the inventory's operation buckets.

    Existing generated entries are removed by method/path before fragment data
    is added, making regeneration idempotent while allowing the checked-in
    inventory to remain a generated artifact.
    """
    merged = dict(inventory)
    raw_operations = _validated_operations(inventory)
    raw_full = _object(inventory.get("full_surface"), "full_surface")
    buckets: dict[str, list[dict[str, object]]] = {
        "operations": raw_operations,
        "v1_operations": _validated_named_operations(
            raw_full.get("v1_operations"), "full_surface.v1_operations"
        ),
        "unversioned_operations": _validated_named_operations(
            raw_full.get("unversioned_operations"), "full_surface.unversioned_operations"
        ),
    }
    for bucket, operations in buckets.items():
        buckets[bucket] = [
            operation
            for operation in operations
            if not any(
                re.fullmatch(pattern, _string(operation["path"], "operation.path"))
                for fragment in fragments
                for pattern in fragment.owned_path_patterns
            )
        ]
    for fragment in fragments:
        for operation in fragment.operations:
            bucket = _string(operation.get("bucket"), "fragment.bucket")
            if _optional_bool(
                operation.get("exclude_from_inventory"),
                "fragment.exclude_from_inventory",
            ):
                continue
            source = dict(operation)
            source.pop("bucket", None)
            source.pop("dest", None)
            source.pop("src", None)
            source.pop("exclude_from_inventory", None)
            buckets[bucket].append(source)
    buckets["operations"].sort(key=lambda item: (item["path"], item["method"]))
    for bucket in ("v1_operations", "unversioned_operations"):
        buckets[bucket].sort(key=lambda item: (item["path"], item["method"]))
    merged["operations"] = buckets["operations"]
    merged["full_surface"] = {
        **raw_full,
        "v1_operations": buckets["v1_operations"],
        "unversioned_operations": buckets["unversioned_operations"],
    }
    return merged


def _resolve_previous_destination(
    method: str,
    route_path: str,
    routes: list[VercelRoute],
) -> VercelRoute | None:
    """Find the first previous route matching one fragment operation.

    Args:
        method: HTTP method.
        route_path: Inventory path template.
        routes: Previous Vercel routes in declaration order.

    Returns:
        The matching route, if any.
    """
    concrete = re.sub(r"\{[^}]+\}", "1", route_path)
    for route in routes:
        if route.src is None or re.fullmatch(route.src, concrete) is None:
            continue
        if route.methods and method.upper() not in route.methods:
            continue
        return route
    return None


def _fragment_vercel_groups(
    fragments: list[RouteFragment],
    previous_routes: list[VercelRoute],
) -> list[dict[str, object]]:
    """Group fragment operations into deterministic Vercel routes.

    Args:
        fragments: Family-owned route metadata.
        previous_routes: Previous Vercel routes for dest/src inference.

    Returns:
        Generated routes with native routes first, each sorted by
        ``(src, dest, methods)``. Python groups gain ``OPTIONS``.

    Raises:
        BurndownGenerationError: When a fragment operation declares an
            unknown destination or two groups claim one method/source.
    """
    grouped: dict[tuple[str, str], set[str]] = {}
    for fragment in fragments:
        for operation in fragment.operations:
            method = _string(operation.get("method"), "fragment.method")
            route_path = _string(operation.get("path"), "fragment.path")
            dest: str | None = None
            src: str | None = None
            raw_dest = operation.get("dest")
            raw_src = operation.get("src")
            if raw_dest is not None:
                dest = _optional_dest(raw_dest, "fragment.dest")
            if raw_src is not None:
                src = _optional_src(raw_src, "fragment.src")
            previous = _resolve_previous_destination(method, route_path, previous_routes)
            if dest is None:
                if previous is None or previous.dest is None:
                    raise BurndownGenerationError(
                        f"{method} {route_path} needs dest; previous vercel.json "
                        "has no matching route"
                    )
                dest = previous.dest
            if src is None:
                if previous is not None and previous.src is not None:
                    src = previous.src
                else:
                    src = route_regex_for_path(route_path)
            assert dest is not None and src is not None
            if dest not in VERCEL_DESTINATIONS:
                raise BurndownGenerationError(f"unknown destination {dest!r}")
            grouped.setdefault((src, dest), set()).add(method.upper())
    routes: list[dict[str, object]] = []
    for (src, dest), methods in grouped.items():
        effective = set(methods)
        if dest == PYTHON_DESTINATION:
            effective.add("OPTIONS")
        ordered = [item for item in METHOD_ORDER if item in effective]
        routes.append({"src": src, "methods": ordered, "dest": dest})
    def _sort_key(route: dict[str, object]) -> tuple[str, str, str]:
        raw_methods = route.get("methods")
        methods_str = ""
        if isinstance(raw_methods, list):
            methods_str = ",".join(item for item in raw_methods if isinstance(item, str))
        return (
            _string(route.get("src"), "route.src"),
            _string(route.get("dest"), "route.dest"),
            methods_str,
        )

    native = sorted(
        [r for r in routes if r["dest"] in NATIVE_DESTINATIONS],
        key=_sort_key,
    )
    python = sorted(
        [r for r in routes if r["dest"] == PYTHON_DESTINATION],
        key=_sort_key,
    )
    ordered = native + python
    seen: set[tuple[str, str]] = set()
    for route in ordered:
        src = _string(route.get("src"), "route.src")
        dest = _string(route.get("dest"), "route.dest")
        route_methods = _consumers(route.get("methods"), "route.methods")
        for method in route_methods:
            identity = (src, method)
            if identity in seen and dest in NATIVE_DESTINATIONS:
                raise BurndownGenerationError(
                    f"duplicate native ingress rewrite for {method} {src}"
                )
            seen.add(identity)
    return ordered


def _generate_vercel_document(
    previous: dict[str, object],
    fragments: list[RouteFragment],
) -> dict[str, object]:
    """Regenerate ``vercel.json`` API routes from fragments plus baseline.

    Args:
        previous: Previous ``vercel.json`` document.
        fragments: Family-owned route metadata.

    Returns:
        The new document with API routes in native-before-Python order.

    Raises:
        BurndownGenerationError: When the previous document is malformed.
    """
    raw_routes = previous.get("routes")
    if not isinstance(raw_routes, list):
        raise BurndownGenerationError("vercel.json must define a routes array")
    previous_routes: list[VercelRoute] = []
    previous_full: list[dict[str, object]] = []
    for raw_route in raw_routes:
        if not isinstance(raw_route, dict):
            raise BurndownGenerationError("vercel.json routes must be objects")
        full = {str(key): item for key, item in raw_route.items()}
        previous_full.append(full)
        src = full.get("src")
        dest = full.get("dest")
        raw_methods = full.get("methods")
        methods: tuple[str, ...] = ()
        if raw_methods is not None:
            if not isinstance(raw_methods, list) or not all(
                isinstance(item, str) for item in raw_methods
            ):
                raise BurndownGenerationError("vercel.json route methods must be strings")
            methods = tuple(item for item in raw_methods if isinstance(item, str))
        previous_routes.append(
            VercelRoute(
                src=src if isinstance(src, str) else None,
                dest=dest if isinstance(dest, str) else None,
                methods=methods,
            )
        )
    fragment_routes = _fragment_vercel_groups(fragments, previous_routes)
    fragment_srcs = {str(route["src"]) for route in fragment_routes}
    baseline_natives: list[dict[str, object]] = []
    baseline_pythons: list[dict[str, object]] = []
    non_api: list[dict[str, object]] = []
    catch_all: dict[str, object] | None = None
    for route in previous_full:
        src = route.get("src")
        dest = route.get("dest")
        if src == CATCH_ALL_SRC:
            catch_all = route
            continue
        if dest in NATIVE_DESTINATIONS:
            if src in fragment_srcs:
                continue
            baseline_natives.append(route)
        elif dest == PYTHON_DESTINATION:
            if src in fragment_srcs:
                continue
            baseline_pythons.append(route)
        else:
            non_api.append({str(key): item for key, item in route.items()})
    if catch_all is None or catch_all.get("dest") != CATCH_ALL_DEST:
        raise BurndownGenerationError("catch-all route missing from vercel.json")
    native_fragment = [r for r in fragment_routes if r["dest"] in NATIVE_DESTINATIONS]
    python_fragment = [r for r in fragment_routes if r["dest"] == PYTHON_DESTINATION]
    # Preserve key order src/methods/dest for generated routes.
    generated = [
        {"src": r["src"], "methods": r["methods"], "dest": r["dest"]}
        for r in [*native_fragment, *python_fragment]
    ]
    new_routes: list[dict[str, object]] = [
        *baseline_natives,
        *generated,
        *baseline_pythons,
        catch_all,
        *non_api,
    ]
    # Validate native-before-Python precedence and catch-all placement.
    native_indices = [
        index
        for index, route in enumerate(new_routes)
        if route.get("dest") in NATIVE_DESTINATIONS
        and route.get("src") != CATCH_ALL_SRC
    ]
    python_indices = [
        index for index, route in enumerate(new_routes) if route.get("dest") == PYTHON_DESTINATION
    ]
    catch_index = next(
        (i for i, route in enumerate(new_routes) if route.get("src") == CATCH_ALL_SRC),
        -1,
    )
    if native_indices and python_indices and max(native_indices) > min(python_indices):
        raise BurndownGenerationError("native routes must precede Python exceptions")
    if python_indices and catch_index < max(python_indices):
        raise BurndownGenerationError("Python exceptions must precede catch-all")
    document = {str(key): item for key, item in previous.items()}
    document["routes"] = new_routes
    return document


def _render_vercel_text(document: dict[str, object]) -> str:
    """Render the generated ``vercel.json`` text.

    Args:
        document: Generated document.

    Returns:
        Deterministic JSON text with a trailing newline.
    """
    return json.dumps(document, indent=2) + "\n"


def _render_rewrite_fragment(
    fragments: list[RouteFragment],
    routes: list[VercelRoute],
) -> str:
    """Render family rewrites with every native route before Python routes."""
    paths = {
        _string(operation.get("path"), "fragment.path")
        for fragment in fragments
        for operation in fragment.operations
    }
    selected: list[tuple[int, VercelRoute]] = []
    for index, route in enumerate(routes):
        if (
            route.src is None
            or route.src == CATCH_ALL_SRC
            or route.dest not in (*NATIVE_DESTINATIONS, "/api/index.py")
        ):
            continue
        if any(
            re.fullmatch(route.src, re.sub(r"\{[^}]+\}", "1", route_path))
            for route_path in paths
        ):
            selected.append((index, route))
    native = [route for _, route in selected if route.dest in NATIVE_DESTINATIONS]
    python = [route for _, route in selected if route.dest == "/api/index.py"]
    ordered = native + python
    payload = {
        "generated_by": "scripts/generate_route_burndown.py",
        "source_fragments": [fragment.name for fragment in fragments],
        "routes": [
            {"src": route.src, "methods": list(route.methods), "dest": route.dest}
            for route in ordered
        ],
    }
    return json.dumps(payload, indent=2) + "\n"


def _routes_from_document(document: dict[str, object]) -> list[VercelRoute]:
    """Decode and validate routes from a loaded routing document.

    Args:
        document: Loaded ``vercel.json`` document.

    Returns:
        The validated route list in declaration order.

    Raises:
        BurndownGenerationError: When the routing document is malformed.
    """
    raw_routes = document.get("routes")
    if not isinstance(raw_routes, list):
        raise BurndownGenerationError("vercel.json must define a routes array")
    routes: list[VercelRoute] = []
    for raw_route in raw_routes:
        if not isinstance(raw_route, dict):
            raise BurndownGenerationError("vercel.json routes must be objects")
        src = raw_route.get("src")
        dest = raw_route.get("dest")
        raw_methods = raw_route.get("methods")
        methods: tuple[str, ...] = ()
        if raw_methods is not None:
            if not isinstance(raw_methods, list) or not all(
                isinstance(method, str) for method in raw_methods
            ):
                raise BurndownGenerationError("vercel.json route methods must be strings")
            methods = tuple(item for item in raw_methods if isinstance(item, str))
        routes.append(
            VercelRoute(
                src=src if isinstance(src, str) else None,
                dest=dest if isinstance(dest, str) else None,
                methods=methods,
            )
        )
    return routes


def _load_routes(path: Path) -> list[VercelRoute]:
    """Decode and validate ``vercel.json`` routing.

    Args:
        path: Path to ``vercel.json``.

    Returns:
        The validated route list in declaration order.

    Raises:
        BurndownGenerationError: When the routing document is malformed.
    """
    return _routes_from_document(load_json(path))


def _resolve_destination(
    method: str,
    path: str,
    routes: list[VercelRoute],
) -> str | None:
    """Resolve the first matching Vercel route, respecting HTTP method.

    Args:
        method: HTTP method such as ``"GET"``.
        path: Inventory path template such as ``/api/v2/threads``.
        routes: Vercel routes in declaration order.

    Returns:
        The matching destination, or ``None`` when no route matches.
    """
    concrete = re.sub(r"\{[^}]+\}", "1", path)
    for route in routes:
        if route.src is None or re.fullmatch(route.src, concrete) is None:
            continue
        if route.methods and method.upper() not in route.methods:
            continue
        return route.dest
    return None


def _classify_burndown(
    runtime: str,
    consumers: list[str],
    destination: str,
) -> str:
    """Classify one operation into its burndown status.

    Args:
        runtime: Declared runtime (``native-rust`` or ``python-fastapi``).
        consumers: Known frontend service callers.
        destination: Resolved Vercel destination.

    Returns:
        One of ``native Rust``, ``shadowed by Rust``, ``live transitional
        Python with callers``, or ``unreferenced/orphaned``.

    Raises:
        BurndownGenerationError: When the declared runtime contradicts
            the deployed ingress.
    """
    if runtime == "native-rust":
        if destination not in NATIVE_DESTINATIONS:
            raise BurndownGenerationError(
                f"native-rust operation routes to non-native {destination!r}"
            )
        return "native Rust"
    if runtime == "python-fastapi":
        if destination in NATIVE_DESTINATIONS:
            return "shadowed by Rust"
        if consumers:
            return "live transitional Python with callers"
        return "unreferenced/orphaned"
    raise BurndownGenerationError(f"unknown runtime {runtime!r}")


def _validated_operations(
    inventory: dict[str, object],
) -> list[dict[str, object]]:
    """Load and validate the inventory operations.

    Args:
        inventory: Loaded inventory document.

    Returns:
        The operation list.

    Raises:
        BurndownGenerationError: When the inventory document is malformed.
    """
    raw_operations = inventory.get("operations")
    if not isinstance(raw_operations, list):
        raise BurndownGenerationError("inventory must define an operations array")
    operations: list[dict[str, object]] = []
    for index, raw_operation in enumerate(raw_operations):
        operation = _object(raw_operation, f"operations[{index}]")
        _string(operation.get("method"), f"operations[{index}].method")
        _string(operation.get("path"), f"operations[{index}].path")
        _string(operation.get("runtime"), f"operations[{index}].runtime")
        _string(operation.get("status"), f"operations[{index}].status")
        _owner(operation.get("owning_issue"), f"operations[{index}].owning_issue")
        _consumers(operation.get("consumers"), f"operations[{index}].consumers")
        operations.append(operation)
    return operations


def _enrich_operations(
    operations: list[dict[str, object]],
    routes: list[VercelRoute],
) -> list[dict[str, object]]:
    """Attach ingress and burndown fields to every operation.

    Args:
        operations: Validated inventory operations.
        routes: Vercel routes for ingress resolution.

    Returns:
        Enriched operations preserving input order.

    Raises:
        BurndownGenerationError: When an operation has no ingress or the
            declared runtime contradicts the ingress.
    """
    enriched: list[dict[str, object]] = []
    for operation in operations:
        method = _string(operation.get("method"), "method")
        path = _string(operation.get("path"), "path")
        runtime = _string(operation.get("runtime"), "runtime")
        consumers = _consumers(operation.get("consumers"), "consumers")
        destination = _resolve_destination(method, path, routes)
        if destination is None:
            raise BurndownGenerationError(f"{method} {path} has no vercel.json route")
        status = _classify_burndown(runtime, consumers, destination)
        entry: dict[str, object] = dict(operation)
        entry["ingress_destination"] = destination
        entry["burndown_status"] = status
        entry["verified_against"] = "vercel.json"
        enriched.append(entry)
    return enriched


def _burndown_summary(enriched: list[dict[str, object]]) -> dict[str, object]:
    """Summarize burndown counts for the inventory header.

    Args:
        enriched: Enriched operations.

    Returns:
        The deterministic burndown summary object.
    """
    def _count(status: str) -> int:
        return sum(1 for item in enriched if item.get("burndown_status") == status)

    total = len(enriched)
    native = sum(1 for item in enriched if item.get("runtime") == "native-rust")
    python_total = total - native
    return {
        "generated_by": "scripts/generate_route_burndown.py",
        "issue": BURN_DOWN_ISSUE,
        "ingress_source": "vercel.json",
        "total_live_operations": total,
        "native_rust": native,
        "python_fastapi": python_total,
        "native_rust_status": _count("native Rust"),
        "shadowed_by_rust": _count("shadowed by Rust"),
        "live_transitional_python_with_callers": _count(
            "live transitional Python with callers"
        ),
        "unreferenced_or_orphaned": _count("unreferenced/orphaned"),
    }


