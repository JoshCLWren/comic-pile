#!/usr/bin/env python3
"""Regenerate the v2 route burndown from deployed ingress.

The burndown is derived from two checked-in sources only:

* ``docs/api/v2-route-inventory.json`` declares every live ``/api/v2``
  operation plus the full Python-handler surface (``v1`` and unversioned
  operations, the catch-all ingress, and the orphan
  ``GET /api/v2/reading-boundaries/{thread_id}``), each with its runtime,
  status, known callers, and cutover owner, and
* ``vercel.json`` declares the deployed ingress destination for each
  method/path.

For each operation this generator resolves the first matching Vercel route,
classifies the burndown status (native Rust, shadowed by Rust, live
transitional Python with callers, or unreferenced/orphaned), and writes the
result back into the inventory as deterministic ``burndown`` fields plus a
compact runtime summary in ``AGENTS.md`` with a full-surface note pointing
at the JSON inventory. Run without arguments to regenerate, or with
``--check`` to fail when either checked-in file is stale. API version is
not implementation language: the URL segment never implies the runtime.
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
import json
from pathlib import Path
import re
from typing import Final

INVENTORY_PATH: Final = Path("docs/api/v2-route-inventory.json")
VERCEL_PATH: Final = Path("vercel.json")
AGENTS_PATH: Final = Path("AGENTS.md")
NATIVE_DESTINATIONS: Final = frozenset({"/api/native_roll.rs", "/api/native_issue.rs"})
CATCH_ALL_SRC: Final = "/api(?:/.*)?"
CATCH_ALL_DEST: Final = "/api/native_roll.rs"
ORPHAN_METHOD: Final = "GET"
ORPHAN_PATH: Final = "/api/v2/reading-boundaries/{thread_id}"
BURN_DOWN_ISSUE: Final = 4739
AGENTS_BEGIN_MARKER: Final = (
    "<!-- route-burndown:begin "
    "(generated by scripts/generate_route_burndown.py, issue #4739) -->"
)
AGENTS_END_MARKER: Final = "<!-- route-burndown:end -->"


class BurndownGenerationError(ValueError):
    """Raised when the inventory and ingress disagree."""


@dataclass(frozen=True)
class VercelRoute:
    """One validated entry from the ``routes`` array in ``vercel.json``."""

    src: str | None
    dest: str | None
    methods: tuple[str, ...]


def load_json(path: Path) -> dict[str, object]:
    """Load a JSON object from ``path``.

    Args:
        path: JSON file to load.

    Returns:
        A string-keyed object mapping.

    Raises:
        BurndownGenerationError: When the file does not contain a JSON object.
    """
    value: object = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise BurndownGenerationError(f"{path} must contain a JSON object")
    return {str(key): item for key, item in value.items()}


def _object(value: object, context: str) -> dict[str, object]:
    """Narrow ``value`` to a string-keyed JSON object.

    Args:
        value: Value to narrow.
        context: Human-readable context for error messages.

    Returns:
        A string-keyed object mapping.

    Raises:
        BurndownGenerationError: When ``value`` is not a JSON object.
    """
    if not isinstance(value, dict):
        raise BurndownGenerationError(f"{context} must be a JSON object")
    return {str(key): item for key, item in value.items()}


def _string(value: object, context: str) -> str:
    """Narrow ``value`` to a string.

    Args:
        value: Value to narrow.
        context: Human-readable context for error messages.

    Returns:
        The string value.

    Raises:
        BurndownGenerationError: When ``value`` is not a string.
    """
    if not isinstance(value, str):
        raise BurndownGenerationError(f"{context} must be a string")
    return value


def _consumers(value: object, context: str) -> list[str]:
    """Narrow ``value`` to a list of caller paths.

    Args:
        value: Value to narrow.
        context: Human-readable context for error messages.

    Returns:
        The caller path list.

    Raises:
        BurndownGenerationError: When ``value`` is not a list of strings.
    """
    if not isinstance(value, list) or not all(isinstance(item, str) for item in value):
        raise BurndownGenerationError(f"{context} must be an array of strings")
    return [item for item in value if isinstance(item, str)]


def _owner(value: object, context: str) -> int | None:
    """Narrow ``value`` to an owning issue number or ``None``.

    Args:
        value: Value to narrow.
        context: Human-readable context for error messages.

    Returns:
        The owning issue number, if any.

    Raises:
        BurndownGenerationError: When ``value`` is neither int nor ``None``.
    """
    if value is None:
        return None
    if not isinstance(value, int):
        raise BurndownGenerationError(f"{context} must be an integer or null")
    return value


def _load_routes(path: Path) -> list[VercelRoute]:
    """Decode and validate ``vercel.json`` routing.

    Args:
        path: Path to ``vercel.json``.

    Returns:
        The validated route list in declaration order.

    Raises:
        BurndownGenerationError: When the routing document is malformed.
    """
    document = load_json(path)
    raw_routes = document.get("routes")
    if not isinstance(raw_routes, list):
        raise BurndownGenerationError("vercel.json must define a routes array")
    routes: list[VercelRoute] = []
    for raw_route in raw_routes:
        if not isinstance(raw_route, dict):
            raise BurndownGenerationError("vercel.json routes must be objects")
        src = raw_route.get("src")
        dest = raw_route.get("dest")
        raw_methods = raw_route.get("methods")
        methods: tuple[str, ...] = ()
        if raw_methods is not None:
            if not isinstance(raw_methods, list) or not all(
                isinstance(method, str) for method in raw_methods
            ):
                raise BurndownGenerationError("vercel.json route methods must be strings")
            methods = tuple(item for item in raw_methods if isinstance(item, str))
        routes.append(
            VercelRoute(
                src=src if isinstance(src, str) else None,
                dest=dest if isinstance(dest, str) else None,
                methods=methods,
            )
        )
    return routes


def _resolve_destination(
    method: str,
    path: str,
    routes: list[VercelRoute],
) -> str | None:
    """Resolve the first matching Vercel route, respecting HTTP method.

    Args:
        method: HTTP method such as ``"GET"``.
        path: Inventory path template such as ``/api/v2/threads``.
        routes: Vercel routes in declaration order.

    Returns:
        The matching destination, or ``None`` when no route matches.
    """
    concrete = re.sub(r"\{[^}]+\}", "1", path)
    for route in routes:
        if route.src is None or re.fullmatch(route.src, concrete) is None:
            continue
        if route.methods and method.upper() not in route.methods:
            continue
        return route.dest
    return None


def _classify_burndown(
    runtime: str,
    consumers: list[str],
    destination: str,
) -> str:
    """Classify one operation into its burndown status.

    Args:
        runtime: Declared runtime (``native-rust`` or ``python-fastapi``).
        consumers: Known frontend service callers.
        destination: Resolved Vercel destination.

    Returns:
        One of ``native Rust``, ``shadowed by Rust``, ``live transitional
        Python with callers``, or ``unreferenced/orphaned``.

    Raises:
        BurndownGenerationError: When the declared runtime contradicts
            the deployed ingress.
    """
    if runtime == "native-rust":
        if destination not in NATIVE_DESTINATIONS:
            raise BurndownGenerationError(
                f"native-rust operation routes to non-native {destination!r}"
            )
        return "native Rust"
    if runtime == "python-fastapi":
        if destination in NATIVE_DESTINATIONS:
            return "shadowed by Rust"
        if consumers:
            return "live transitional Python with callers"
        return "unreferenced/orphaned"
    raise BurndownGenerationError(f"unknown runtime {runtime!r}")


def _validated_operations(
    inventory: dict[str, object],
) -> list[dict[str, object]]:
    """Load and validate the inventory operations.

    Args:
        inventory: Loaded inventory document.

    Returns:
        The operation list.

    Raises:
        BurndownGenerationError: When the inventory document is malformed.
    """
    raw_operations = inventory.get("operations")
    if not isinstance(raw_operations, list):
        raise BurndownGenerationError("inventory must define an operations array")
    operations: list[dict[str, object]] = []
    for index, raw_operation in enumerate(raw_operations):
        operation = _object(raw_operation, f"operations[{index}]")
        _string(operation.get("method"), f"operations[{index}].method")
        _string(operation.get("path"), f"operations[{index}].path")
        _string(operation.get("runtime"), f"operations[{index}].runtime")
        _string(operation.get("status"), f"operations[{index}].status")
        _owner(operation.get("owning_issue"), f"operations[{index}].owning_issue")
        _consumers(operation.get("consumers"), f"operations[{index}].consumers")
        operations.append(operation)
    return operations


def _enrich_operations(
    operations: list[dict[str, object]],
    routes: list[VercelRoute],
) -> list[dict[str, object]]:
    """Attach ingress and burndown fields to every operation.

    Args:
        operations: Validated inventory operations.
        routes: Vercel routes for ingress resolution.

    Returns:
        Enriched operations preserving input order.

    Raises:
        BurndownGenerationError: When an operation has no ingress or the
            declared runtime contradicts the ingress.
    """
    enriched: list[dict[str, object]] = []
    for operation in operations:
        method = _string(operation.get("method"), "method")
        path = _string(operation.get("path"), "path")
        runtime = _string(operation.get("runtime"), "runtime")
        consumers = _consumers(operation.get("consumers"), "consumers")
        destination = _resolve_destination(method, path, routes)
        if destination is None:
            raise BurndownGenerationError(f"{method} {path} has no vercel.json route")
        status = _classify_burndown(runtime, consumers, destination)
        entry: dict[str, object] = dict(operation)
        entry["ingress_destination"] = destination
        entry["burndown_status"] = status
        entry["verified_against"] = "vercel.json"
        enriched.append(entry)
    return enriched


def _burndown_summary(enriched: list[dict[str, object]]) -> dict[str, object]:
    """Summarize burndown counts for the inventory header.

    Args:
        enriched: Enriched operations.

    Returns:
        The deterministic burndown summary object.
    """
    def _count(status: str) -> int:
        return sum(1 for item in enriched if item.get("burndown_status") == status)

    total = len(enriched)
    native = sum(1 for item in enriched if item.get("runtime") == "native-rust")
    python_total = total - native
    return {
        "generated_by": "scripts/generate_route_burndown.py",
        "issue": BURN_DOWN_ISSUE,
        "ingress_source": "vercel.json",
        "total_live_operations": total,
        "native_rust": native,
        "python_fastapi": python_total,
        "native_rust_status": _count("native Rust"),
        "shadowed_by_rust": _count("shadowed by Rust"),
        "live_transitional_python_with_callers": _count(
            "live transitional Python with callers"
        ),
        "unreferenced_or_orphaned": _count("unreferenced/orphaned"),
    }


def _validated_named_operations(
    value: object,
    context: str,
) -> list[dict[str, object]]:
    """Validate one named full-surface operation list.

    Args:
        value: Raw JSON value for the operation list.
        context: Human-readable context for error messages.

    Returns:
        The validated operation list.

    Raises:
        BurndownGenerationError: When the list is malformed.
    """
    if not isinstance(value, list):
        raise BurndownGenerationError(f"{context} must be an array")
    operations: list[dict[str, object]] = []
    for index, raw_operation in enumerate(value):
        operation = _object(raw_operation, f"{context}[{index}]")
        _string(operation.get("method"), f"{context}[{index}].method")
        _string(operation.get("path"), f"{context}[{index}].path")
        _string(operation.get("runtime"), f"{context}[{index}].runtime")
        _string(operation.get("status"), f"{context}[{index}].status")
        _owner(operation.get("owning_issue"), f"{context}[{index}].owning_issue")
        _consumers(operation.get("consumers"), f"{context}[{index}].consumers")
        operations.append(operation)
    return operations


