def main() -> int:
    """Generate or verify the burndown inventory, AGENTS section, and ingress.

    Returns:
        Process exit code: 0 when up to date (or written), 1 when
        ``--check`` detects stale output, 2 on generation errors.
    """
    args = _parse_args()
    try:
        inventory = load_json(args.inventory)
        fragments = _load_route_fragments(args.fragments)
        previous_vercel = load_json(args.vercel)
        vercel_document = _generate_vercel_document(previous_vercel, fragments)
        vercel_text = _render_vercel_text(vercel_document)
        routes = _routes_from_document(vercel_document)
        payload, inventory_text = _render_inventory(inventory, routes, fragments)
        merged_inventory = _merge_route_fragments(inventory, fragments)
        enriched_operations = _enrich_operations(
            _validated_operations(merged_inventory), routes
        )
        rewrite_text = _render_rewrite_fragment(fragments, routes)
        full_surface = payload.get("full_surface")
        full_summary: dict[str, object] | None = None
        if isinstance(full_surface, dict):
            raw_summary = full_surface.get("summary")
            if isinstance(raw_summary, dict):
                full_summary = {
                    str(key): item for key, item in raw_summary.items()
                }
        block = _render_agents_block(enriched_operations, full_summary)
        agents_original = args.agents.read_text(encoding="utf-8")
        agents_text = _render_agents_text(agents_original, block)
    except BurndownGenerationError as exc:
        print(f"burndown generation failed: {exc}")
        return 2

    if args.check:
        inventory_current = args.inventory.read_text(encoding="utf-8")
        vercel_current = args.vercel.read_text(encoding="utf-8")
        agents_current = args.agents.read_text(encoding="utf-8")
        rewrite_current = args.rewrite_fragment.read_text(encoding="utf-8")
        if (
            inventory_current != inventory_text
            or vercel_current != vercel_text
            or agents_current != agents_text
            or rewrite_current != rewrite_text
        ):
            print(
                "Route burndown is stale; run "
                "`python3 scripts/generate_route_burndown.py` and commit the result."
            )
            return 1
        print(
            f"Verified route burndown: {args.inventory}, {args.vercel}, "
            f"{args.agents}, and {args.rewrite_fragment}"
        )
        return 0

    args.inventory.write_text(inventory_text, encoding="utf-8")
    args.vercel.write_text(vercel_text, encoding="utf-8")
    args.agents.write_text(agents_text, encoding="utf-8")
    args.rewrite_fragment.write_text(rewrite_text, encoding="utf-8")
    print(
        f"Wrote route burndown: {args.inventory}, {args.vercel}, "
        f"{args.agents}, and {args.rewrite_fragment}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
