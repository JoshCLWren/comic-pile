"""Regression tests for the taste-discovery family route contract (issue #4853).

The browser-called taste family is served by the native Rust runtime at its
existing method and path:

* ``GET /api/v1/taste/discoveries``
* ``POST /api/v1/taste/discoveries/{signal_id}/dismiss``

``POST .../dismiss`` lost its Python handler in #5162, so it is retired from
the generated Python-handler surface while it stays declared and natively
routed. ``GET .../discoveries`` keeps its Python handler until the cutover is
proven in production, so it stays in that surface and the family fragment
routes it natively.

These assertions deliberately avoid the generated bytes of
``docs/api/v2-route-inventory.json`` and ``vercel.json``: the post-merge route
bot regenerates both, so pinning their pre-merge bytes would fail every
cutover until that bot runs. The contract asserted here holds in both the
pre-merge and the regenerated state.
"""

from __future__ import annotations

from pathlib import Path

from scripts.generate_route_burndown import (
    FRAGMENT_DIR,
    RouteFragment,
    _generate_vercel_document,
    _load_route_fragments,
    _load_routes,
    _resolve_destination,
    _routes_from_document,
    load_json,
)

ROOT = Path(__file__).resolve().parents[1]
INVENTORY_PATH = ROOT / "docs" / "api" / "v2-route-inventory.json"
VERCEL_PATH = ROOT / "vercel.json"

LISTING_PATH = "/api/v1/taste/discoveries"
DISMISS_PATH = "/api/v1/taste/discoveries/{signal_id}/dismiss"
NATIVE_DESTINATION = "/api/native_roll.rs"
TASTE_CONSUMER = "frontend/src/services/api-taste.ts"


def _taste_fragment() -> RouteFragment:
    """Return the taste-discovery family route fragment.

    Returns:
        The loaded ``taste-discoveries`` route fragment.

    Raises:
        AssertionError: When the family fragment is missing.
    """
    for fragment in _load_route_fragments(FRAGMENT_DIR):
        if fragment.name == "taste-discoveries":
            return fragment
    raise AssertionError("missing taste-discoveries route fragment")


def _v1_operations() -> list[dict[str, object]]:
    """Return the generated ``/api/v1`` Python-handler surface.

    Returns:
        The validated ``full_surface.v1_operations`` entries.

    Raises:
        AssertionError: When the inventory shape is unexpected.
    """
    inventory = load_json(INVENTORY_PATH)
    full_surface = inventory["full_surface"]
    assert isinstance(full_surface, dict)
    raw_operations = full_surface["v1_operations"]
    assert isinstance(raw_operations, list)
    return [item for item in raw_operations if isinstance(item, dict)]


def test_taste_family_declares_both_browser_called_operations() -> None:
    """The family declares both browser-called operations on the native runtime."""
    fragment = _taste_fragment()
    declared = {
        (operation["method"], operation["path"], operation["dest"])
        for operation in fragment.operations
    }
    assert declared == {
        ("GET", LISTING_PATH, NATIVE_DESTINATION),
        ("POST", DISMISS_PATH, NATIVE_DESTINATION),
    }
    for operation in fragment.operations:
        consumers = operation["consumers"]
        assert isinstance(consumers, list)
        assert consumers == [TASTE_CONSUMER]
        assert operation["owning_issue"] == 4853


def test_dismiss_operation_is_retired_from_the_python_surface_only() -> None:
    """The retired Python dismiss handler leaves the surface, not the ingress."""
    assert not any(
        operation["method"] == "POST" and operation["path"] == DISMISS_PATH
        for operation in _v1_operations()
    ), "the retired Python dismiss handler must stay out of the Python surface"
    routes = _load_routes(VERCEL_PATH)
    assert _resolve_destination("POST", DISMISS_PATH, routes) == NATIVE_DESTINATION


def test_discovery_listing_stays_declared_and_routes_natively_after_regeneration() -> None:
    """The listing keeps its surface entry while the fragment routes it natively."""
    matches = [
        operation
        for operation in _v1_operations()
        if operation["method"] == "GET" and operation["path"] == LISTING_PATH
    ]
    assert len(matches) == 1
    consumers = matches[0]["consumers"]
    assert isinstance(consumers, list)
    assert consumers == [TASTE_CONSUMER]

    fragments = _load_route_fragments(FRAGMENT_DIR)
    regenerated = _generate_vercel_document(load_json(VERCEL_PATH), fragments)
    regenerated_routes = _routes_from_document(regenerated)
    assert (
        _resolve_destination("GET", LISTING_PATH, regenerated_routes) == NATIVE_DESTINATION
    )
