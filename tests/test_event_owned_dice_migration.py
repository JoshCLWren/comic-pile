"""Regression tests for the event-ownership migration (``c44050000001``).

The application test schema is built with ``Base.metadata.create_all``, which
never installs the migration's backfill or ownership trigger. These tests run
the real Alembic revision against a dedicated PostgreSQL schema so the
data-safety guarantees are exercised instead of assumed:

* historical ownership is recovered from every surviving reference;
* unattributable historical rows stay intact with ``NULL`` ownership;
* conflicting cross-reader references are not silently assigned;
* deleting a session nulls its event link instead of deleting owned history;
* the trigger infers, verifies, and freezes ownership for legacy writers.
"""

from __future__ import annotations

import importlib.util
import os
import uuid
from pathlib import Path
from types import ModuleType

import pytest
from alembic.migration import MigrationContext
from alembic.operations import Operations
from sqlalchemy import text
from sqlalchemy.exc import DBAPIError
from sqlalchemy.ext.asyncio import AsyncConnection, AsyncEngine

MIGRATION_PATH = (
    Path(__file__).parents[1] / "alembic/versions/c44050000001_event_owned_roll_dice.py"
)

ALICE = 1
BOB = 2
ALICE_SESSION = 10
ALICE_THREAD = 100
BOB_THREAD = 200
ALICE_SELECTED_THREAD = 300
ALICE_ISSUE = 1000
BOB_ISSUE = 2000


def _load_migration() -> ModuleType:
    """Load the event-ownership migration module under test.

    Returns:
        The imported migration module.
    """
    spec = importlib.util.spec_from_file_location(
        "event_owned_roll_dice_migration", MIGRATION_PATH
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _fixture_schema() -> str:
    """Return a unique schema name for the migration fixture.

    Returns:
        A schema name that no other test run can collide with.
    """
    return f"test_event_owner_{os.getpid()}_{uuid.uuid4().hex[:8]}"


def _sqlstate(error: DBAPIError) -> str | None:
    """Return the PostgreSQL SQLSTATE for a database error, when available.

    Args:
        error: The SQLAlchemy database error raised by the driver.

    Returns:
        The five-character SQLSTATE, or ``None`` when the driver omitted it.
    """
    original = error.orig
    for attribute in ("sqlstate", "pgcode"):
        value = getattr(original, attribute, None)
        if isinstance(value, str):
            return value
    return None


async def _create_pre_migration_schema(connection: AsyncConnection, schema: str) -> None:
    """Create the schema as it existed before this migration ran.

    Args:
        connection: Connection used to build the fixture.
        schema: Schema that holds the fixture.
    """
    await connection.execute(text(f'DROP SCHEMA IF EXISTS "{schema}" CASCADE'))
    await connection.execute(text(f'CREATE SCHEMA "{schema}"'))
    await connection.execute(
        text(
            f'CREATE TABLE "{schema}".users (id integer PRIMARY KEY)'
        )
    )
    await connection.execute(
        text(
            f'CREATE TABLE "{schema}".sessions '
            "(id integer PRIMARY KEY, user_id integer NOT NULL)"
        )
    )
    await connection.execute(
        text(
            f'CREATE TABLE "{schema}".threads '
            "(id integer PRIMARY KEY, user_id integer NOT NULL)"
        )
    )
    await connection.execute(
        text(
            f'CREATE TABLE "{schema}".issues '
            "(id integer PRIMARY KEY, thread_id integer NOT NULL)"
        )
    )
    # Mirrors the pre-migration events shape and constraint names, including
    # the cascading session link this migration replaces with SET NULL.
    await connection.execute(
        text(
            f'CREATE TABLE "{schema}".events ('
            "id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            "type text NOT NULL, "
            "timestamp timestamptz NOT NULL DEFAULT NOW(), "
            "die integer, "
            "die_after integer, "
            "rating double precision, "
            "context json, "
            "session_id integer, "
            "thread_id integer, "
            "issue_id integer, "
            "selected_thread_id integer, "
            "source_roll_event_id integer, "
            'CONSTRAINT events_session_id_fkey FOREIGN KEY (session_id) '
            f'REFERENCES "{schema}".sessions (id) ON DELETE CASCADE, '
            'CONSTRAINT events_thread_id_fkey FOREIGN KEY (thread_id) '
            f'REFERENCES "{schema}".threads (id) ON DELETE CASCADE, '
            'CONSTRAINT events_issue_id_fkey FOREIGN KEY (issue_id) '
            f'REFERENCES "{schema}".issues (id) ON DELETE SET NULL, '
            'CONSTRAINT events_source_roll_event_id_fkey FOREIGN KEY '
            f'(source_roll_event_id) REFERENCES "{schema}".events (id) ON DELETE SET NULL'
            ")"
        )
    )
    await connection.execute(
        text(
            f'INSERT INTO "{schema}".users (id) VALUES (:alice), (:bob)'
        ),
        {"alice": ALICE, "bob": BOB},
    )
    await connection.execute(
        text(
            f'INSERT INTO "{schema}".sessions (id, user_id) VALUES (:id, :owner)'
        ),
        {"id": ALICE_SESSION, "owner": ALICE},
    )
    await connection.execute(
        text(
            f'INSERT INTO "{schema}".threads (id, user_id) VALUES '
            "(:alice_thread, :alice), (:bob_thread, :bob), "
            "(:selected, :alice)"
        ),
        {
            "alice_thread": ALICE_THREAD,
            "bob_thread": BOB_THREAD,
            "selected": ALICE_SELECTED_THREAD,
            "alice": ALICE,
            "bob": BOB,
        },
    )
    await connection.execute(
        text(
            f'INSERT INTO "{schema}".issues (id, thread_id) VALUES '
            "(:alice_issue, :alice_thread), (:bob_issue, :bob_thread)"
        ),
        {
            "alice_issue": ALICE_ISSUE,
            "bob_issue": BOB_ISSUE,
            "alice_thread": ALICE_THREAD,
            "bob_thread": BOB_THREAD,
        },
    )
    # 1: session-owned, 2: detached thread, 3: detached issue, 4: selected
    # thread, 5: source roll event, 6: unattributable historical delete,
    # 7: corrupt cross-reader session+thread, 8: detached Bob thread.
    await connection.execute(
        text(
            f'INSERT INTO "{schema}".events '
            "(id, type, session_id, thread_id, issue_id, selected_thread_id, "
            "source_roll_event_id) VALUES "
            "(1, 'roll', :session, NULL, NULL, NULL, NULL), "
            "(2, 'rate', NULL, :alice_thread, NULL, NULL, NULL), "
            "(3, 'rate', NULL, NULL, :alice_issue, NULL, NULL), "
            "(4, 'dismiss', NULL, NULL, NULL, :selected, NULL), "
            "(5, 'rate', NULL, NULL, NULL, NULL, 1), "
            "(6, 'delete', NULL, NULL, NULL, NULL, NULL), "
            "(7, 'rate', :session, :bob_thread, NULL, NULL, NULL), "
            "(8, 'rate', NULL, :bob_thread, NULL, NULL, NULL)"
        ),
        {
            "session": ALICE_SESSION,
            "alice_thread": ALICE_THREAD,
            "alice_issue": ALICE_ISSUE,
            "selected": ALICE_SELECTED_THREAD,
            "bob_thread": BOB_THREAD,
        },
    )
    # Explicit historical ids do not advance the identity sequence; move it to
    # the seeded maximum so trigger probes cannot collide with fixture rows.
    await connection.execute(
        text(
            f"SELECT setval(pg_get_serial_sequence('{schema}.events', 'id'), "
            f'(SELECT MAX(id) FROM "{schema}".events))'
        )
    )
    await connection.commit()


async def _drop_fixture_schema(connection: AsyncConnection, schema: str) -> None:
    """Drop the fixture schema.

    Args:
        connection: Connection used to drop the fixture.
        schema: Schema that holds the fixture.
    """
    await connection.rollback()
    await connection.execute(text(f'DROP SCHEMA IF EXISTS "{schema}" CASCADE'))
    await connection.commit()


def _run_upgrade(module: ModuleType, schema: str):
    """Build a callable that runs the migration upgrade against a schema.

    Args:
        module: The migration module under test.
        schema: Schema that holds the fixture.

    Returns:
        A callable that takes a synchronous connection and runs ``upgrade``.
    """

    def run(sync_connection) -> None:
        """Run the migration upgrade against the fixture schema."""
        sync_connection.execute(text(f'SET search_path TO "{schema}"'))
        sync_connection.commit()
        migration_context = MigrationContext.configure(sync_connection)
        with Operations.context(migration_context), migration_context.begin_transaction():
            module.upgrade()

    return run


async def _owners(connection: AsyncConnection, schema: str) -> dict[int, int | None]:
    """Return the migrated owner of every fixture event.

    Args:
        connection: Connection used to read the fixture.
        schema: Schema that holds the fixture.

    Returns:
        Mapping of event id to its migrated ``user_id``.
    """
    rows = await connection.execute(
        text(f'SELECT id, user_id FROM "{schema}".events ORDER BY id')
    )
    return {int(row.id): row.user_id for row in rows}


async def _insert_event(
    connection: AsyncConnection,
    schema: str,
    *,
    event_type: str,
    user_id: int | None = None,
    session_id: int | None = None,
    thread_id: int | None = None,
) -> str:
    """Insert one event and return ``ok`` or the raised SQLSTATE.

    Args:
        connection: Connection used for the probe.
        schema: Schema that holds the fixture.
        event_type: Event type to write.
        user_id: Explicit owner, when supplied.
        session_id: Session reference, when supplied.
        thread_id: Thread reference, when supplied.

    Returns:
        ``ok`` on success, otherwise the PostgreSQL SQLSTATE.
    """
    try:
        await connection.execute(
            text(
                f'INSERT INTO "{schema}".events '
                "(type, user_id, session_id, thread_id) "
                "VALUES (:type, :user_id, :session_id, :thread_id)"
            ),
            {
                "type": event_type,
                "user_id": user_id,
                "session_id": session_id,
                "thread_id": thread_id,
            },
        )
        await connection.commit()
    except DBAPIError as error:
        await connection.rollback()
        return _sqlstate(error) or "error"
    return "ok"


@pytest.mark.asyncio
async def test_migration_backfills_ownership_and_preserves_unattributable_history(
    db_engine: AsyncEngine,
) -> None:
    """The real migration recovers owners without deleting or inventing history."""
    module = _load_migration()
    schema = _fixture_schema()
    worker = await db_engine.connect()
    try:
        await _create_pre_migration_schema(worker, schema)
        await worker.run_sync(_run_upgrade(module, schema))

        owners = await _owners(worker, schema)
        assert owners == {
            1: ALICE,  # session reference
            2: ALICE,  # detached thread reference
            3: ALICE,  # detached issue -> thread reference
            4: ALICE,  # selected thread reference
            5: ALICE,  # source roll event reference
            6: None,  # unattributable historical delete
            7: None,  # conflicting session/thread owners stay unassigned
            8: BOB,  # detached thread owned by another reader
        }

        # The session link must null out instead of cascading the owned event.
        delete_action = await worker.execute(
            text(
                "SELECT confdeltype FROM pg_constraint "
                "WHERE conname = 'events_session_id_fkey' "
                "AND connamespace = (SELECT oid FROM pg_namespace "
                "WHERE nspname = :schema)"
            ),
            {"schema": schema},
        )
        assert delete_action.scalar_one() in (b"n", "n")

        index_state = await worker.execute(
            text(
                "SELECT i.indisvalid FROM pg_index i "
                "JOIN pg_class c ON c.oid = i.indexrelid "
                "JOIN pg_namespace n ON n.oid = c.relnamespace "
                "WHERE c.relname = :name AND n.nspname = :schema"
            ),
            {"name": "ix_event_user_timestamp_id", "schema": schema},
        )
        assert index_state.scalar_one() is True

        await worker.execute(
            text(f'DELETE FROM "{schema}".sessions WHERE id = :id'),
            {"id": ALICE_SESSION},
        )
        await worker.commit()
        preserved = (
            await worker.execute(
                text(
                    f'SELECT user_id, session_id FROM "{schema}".events '
                    "WHERE id = 1"
                )
            )
        ).one()
        assert preserved.user_id == ALICE
        assert preserved.session_id is None
    finally:
        await _drop_fixture_schema(worker, schema)
        await worker.close()


@pytest.mark.asyncio
async def test_trigger_infers_verifies_and_freezes_event_ownership(
    db_engine: AsyncEngine,
) -> None:
    """Legacy writers keep working while cross-reader linkage fails closed."""
    module = _load_migration()
    schema = _fixture_schema()
    worker = await db_engine.connect()
    try:
        await _create_pre_migration_schema(worker, schema)
        await worker.run_sync(_run_upgrade(module, schema))

        # Legacy session-only and thread-only writers infer the owner.
        assert (
            await _insert_event(
                worker,
                schema,
                event_type="roll",
                session_id=ALICE_SESSION,
            )
            == "ok"
        )
        assert (
            await _insert_event(
                worker,
                schema,
                event_type="rate",
                thread_id=ALICE_THREAD,
            )
            == "ok"
        )
        # A reference-free sessionless event requires an explicit owner.
        assert (
            await _insert_event(worker, schema, event_type="delete")
            == "23502"
        )
        assert (
            await _insert_event(
                worker, schema, event_type="delete", user_id=BOB
            )
            == "ok"
        )
        # An explicit owner that disagrees with an owned reference is rejected.
        assert (
            await _insert_event(
                worker,
                schema,
                event_type="rate",
                user_id=BOB,
                thread_id=ALICE_THREAD,
            )
            == "23514"
        )
        # Mixed references from two readers never link across accounts.
        assert (
            await _insert_event(
                worker,
                schema,
                event_type="rate",
                session_id=ALICE_SESSION,
                thread_id=BOB_THREAD,
            )
            == "23514"
        )

        # Ownership is immutable once recorded.
        with pytest.raises(DBAPIError) as immutable:
            await worker.execute(
                text(
                    f'UPDATE "{schema}".events SET user_id = :owner WHERE id = 2'
                ),
                {"owner": BOB},
            )
        assert _sqlstate(immutable.value) == "23514"
        await worker.rollback()

        # Re-pointing an owned event at another reader's thread is rejected.
        with pytest.raises(DBAPIError) as relink:
            await worker.execute(
                text(
                    f'UPDATE "{schema}".events SET thread_id = :thread WHERE id = 2'
                ),
                {"thread": BOB_THREAD},
            )
        assert _sqlstate(relink.value) == "23514"
        await worker.rollback()
    finally:
        await _drop_fixture_schema(worker, schema)
        await worker.close()
