//! End-to-end HTTP regressions through the real mounted native auth router.
//!
//! These requests enter the production Axum router (middleware included) rather
//! than calling handlers directly, so CSRF exemptions, cookie paths, refresh
//! rotation and the recovery surface are exercised as deployed.

use axum::{
    body::{to_bytes, Body},
    http::{header, Request, StatusCode},
};
use comicpile_roll_service::{auth::BackgroundTasks, config::Config, router, AppState};
use serde_json::Value;
use std::future::Future;
use std::pin::Pin;
use std::sync::atomic::{AtomicUsize, Ordering};
use std::sync::{Arc, Mutex};
use tower::ServiceExt;

const SECRET: &str = "synthetic-auth-http-secret";

/// A recovery-delivery future captured by the test registrar.
type DeliveryFuture = Pin<Box<dyn Future<Output = ()> + Send>>;

async fn schema() -> (String, String) {
    let base = std::env::var("RUST_ROLL_TEST_DATABASE_URL")
        .expect("disposable RUST_ROLL_TEST_DATABASE_URL required; tests never silently skip");
    let (admin, connection) = tokio_postgres::connect(&base, tokio_postgres::NoTls)
        .await
        .expect("disposable Postgres");
    tokio::spawn(async move {
        let _ = connection.await;
    });
    let nanos = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap()
        .as_nanos();
    let name = format!("auth_http_{}_{}", std::process::id(), nanos);
    admin
        .batch_execute(&format!(
            "CREATE SCHEMA {name};
             CREATE TABLE {name}.users (
                 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                 username text UNIQUE NOT NULL,
                 email text,
                 password_hash text,
                 is_admin boolean NOT NULL DEFAULT false,
                 password_changed_at timestamptz,
                 created_at timestamptz NOT NULL DEFAULT NOW()
             );
             CREATE TABLE {name}.failed_login_attempts (
                 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                 username text NOT NULL,
                 ip_address text NOT NULL,
                 attempted_at timestamptz NOT NULL DEFAULT NOW()
             );
             CREATE TABLE {name}.revoked_tokens (
                 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                 user_id integer NOT NULL,
                 jti text NOT NULL UNIQUE,
                 revoked_at timestamptz NOT NULL DEFAULT NOW(),
                 expires_at timestamptz NOT NULL
             );
             CREATE TABLE {name}.password_reset_tokens (
                 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                 user_id integer NOT NULL,
                 token_digest text NOT NULL UNIQUE,
                 expires_at timestamptz NOT NULL,
                 used_at timestamptz,
                 created_at timestamptz NOT NULL DEFAULT NOW()
             );"
        ))
        .await
        .unwrap();
    let scoped = format!("{base}?options=-c%20search_path%3D{name}");
    (name, scoped)
}

fn state(url: &str) -> Arc<AppState> {
    Arc::new(
        AppState::new(
            Config::from_lookup(|key| match key {
                "RUST_ROLL_DATABASE_URL" => Some(url.into()),
                "RUST_ROLL_JWT_SECRET" => Some(SECRET.into()),
                "RUST_ROLL_POOL_SIZE" => Some("2".into()),
                _ => None,
            })
            .unwrap(),
        )
        .unwrap(),
    )
}

fn post(path: &str, body: Value) -> Request<Body> {
    Request::builder()
        .method("POST")
        .uri(path)
        .header(header::CONTENT_TYPE, "application/json")
        .header("x-forwarded-for", "198.51.100.77")
        .body(Body::from(body.to_string()))
        .unwrap()
}

async fn send(state: &Arc<AppState>, request: Request<Body>) -> (StatusCode, Value, Vec<String>) {
    let response = router(state.clone()).oneshot(request).await.unwrap();
    let status = response.status();
    let cookies = response
        .headers()
        .get_all(header::SET_COOKIE)
        .iter()
        .filter_map(|value| value.to_str().ok().map(str::to_owned))
        .collect::<Vec<_>>();
    let body = to_bytes(response.into_body(), 8192).await.unwrap();
    let body = serde_json::from_slice(&body).unwrap_or(Value::Null);
    (status, body, cookies)
}

#[tokio::test]
async fn mounted_native_auth_surface_round_trips_login_refresh_logout_and_recovery() {
    let (name, url) = schema().await;
    let state = state(&url);

    let (status, registered, _) = send(
        &state,
        post(
            "/api/v1/auth/register",
            serde_json::json!({
                "username": "http-reader",
                "email": "http-reader@example.com",
                "password": "correct-horse-battery"
            }),
        ),
    )
    .await;
    assert_eq!(status, StatusCode::OK, "{registered}");

    let (status, logged_in, cookies) = send(
        &state,
        post(
            "/api/v1/auth/login",
            serde_json::json!({"username": "http-reader", "password": "correct-horse-battery"}),
        ),
    )
    .await;
    assert_eq!(status, StatusCode::OK, "{logged_in}");
    assert!(
        cookies
            .iter()
            .any(|cookie| cookie.starts_with("refresh_token=") && cookie.contains("Path=/api")),
        "live login must scope refresh to /api: {cookies:?}"
    );
    assert!(cookies
        .iter()
        .any(|cookie| cookie.starts_with("csrf_token=")));

    let refresh_token = logged_in["refresh_token"].as_str().unwrap().to_string();
    let access_token = logged_in["access_token"].as_str().unwrap().to_string();
    let csrf = cookies
        .iter()
        .find_map(|cookie| cookie.strip_prefix("csrf_token="))
        .and_then(|rest| rest.split(';').next())
        .unwrap()
        .to_string();

    let (status, rotated, _) = send(
        &state,
        post(
            "/api/v1/auth/refresh",
            serde_json::json!({"refresh_token": refresh_token}),
        ),
    )
    .await;
    assert_eq!(status, StatusCode::OK, "{rotated}");
    assert_ne!(rotated["refresh_token"], refresh_token);

    let (status, _, _) = send(
        &state,
        post(
            "/api/v1/auth/refresh",
            serde_json::json!({"refresh_token": refresh_token}),
        ),
    )
    .await;
    assert_eq!(
        status,
        StatusCode::UNAUTHORIZED,
        "the live route must reject a replayed refresh token"
    );

    let logout = Request::builder()
        .method("POST")
        .uri("/api/v1/auth/logout")
        .header(header::AUTHORIZATION, format!("Bearer {access_token}"))
        .header(header::COOKIE, format!("csrf_token={csrf}"))
        .header("x-csrf-token", csrf.clone())
        .body(Body::empty())
        .unwrap();
    let (status, _, cleared) = send(&state, logout).await;
    assert_eq!(status, StatusCode::OK);
    assert!(
        cleared
            .iter()
            .any(|cookie| cookie.starts_with("refresh_token=") && cookie.contains("Path=/api")),
        "logout must clear the same /api-scoped cookie: {cleared:?}"
    );

    let (status, acknowledgement, _) = send(
        &state,
        post(
            "/api/v1/auth/forgot-password",
            serde_json::json!({"email": "http-reader@example.com"}),
        ),
    )
    .await;
    assert_eq!(status, StatusCode::OK);
    assert_eq!(
        acknowledgement["message"],
        "If an account exists, a reset link has been sent."
    );

    let (status, rejected, _) = send(
        &state,
        post(
            "/api/v1/auth/reset-password",
            serde_json::json!({"token": "not-a-real-token", "new_password": "brand-new-secret"}),
        ),
    )
    .await;
    assert_eq!(status, StatusCode::BAD_REQUEST, "{rejected}");
    assert_eq!(rejected["detail"], "Invalid or expired reset request.");

    let (admin, connection) = tokio_postgres::connect(
        std::env::var("RUST_ROLL_TEST_DATABASE_URL")
            .unwrap()
            .as_str(),
        tokio_postgres::NoTls,
    )
    .await
    .unwrap();
    tokio::spawn(async move {
        let _ = connection.await;
    });
    admin
        .batch_execute(&format!("DROP SCHEMA {name} CASCADE"))
        .await
        .unwrap();
}

#[tokio::test]
async fn forgot_password_registers_delivery_as_tracked_background_work() {
    let (name, url) = schema().await;
    let state = state(&url);

    let (status, registered_body, _) = send(
        &state,
        post(
            "/api/v1/auth/register",
            serde_json::json!({
                "username": "delivery-reader",
                "email": "delivery-reader@example.com",
                "password": "correct-horse-battery"
            }),
        ),
    )
    .await;
    assert_eq!(status, StatusCode::OK, "{registered_body}");

    // A bare `tokio::spawn` would bypass this registrar entirely; on Vercel the
    // invocation could then freeze before SMTP delivery finished.
    let registrations = Arc::new(AtomicUsize::new(0));
    let captured: Arc<Mutex<Option<DeliveryFuture>>> = Arc::new(Mutex::new(None));
    let handle = BackgroundTasks::new({
        let registrations = Arc::clone(&registrations);
        let captured = Arc::clone(&captured);
        move |future| {
            registrations.fetch_add(1, Ordering::SeqCst);
            *captured.lock().unwrap() = Some(future);
        }
    });

    let request = Request::builder()
        .method("POST")
        .uri("/api/v1/auth/forgot-password")
        .header(header::CONTENT_TYPE, "application/json")
        .header("x-forwarded-for", "198.51.100.91")
        .extension(handle)
        .body(Body::from(
            serde_json::json!({"email": "delivery-reader@example.com"}).to_string(),
        ))
        .unwrap();
    let (status, acknowledgement, _) = send(&state, request).await;
    assert_eq!(status, StatusCode::OK);
    assert_eq!(
        acknowledgement["message"],
        "If an account exists, a reset link has been sent."
    );
    assert_eq!(
        registrations.load(Ordering::SeqCst),
        1,
        "recovery delivery must be handed to tracked background work"
    );
    assert!(
        captured.lock().unwrap().is_some(),
        "the registered delivery future must be retained by the runtime registrar"
    );

    let (admin, connection) = tokio_postgres::connect(
        std::env::var("RUST_ROLL_TEST_DATABASE_URL")
            .unwrap()
            .as_str(),
        tokio_postgres::NoTls,
    )
    .await
    .unwrap();
    tokio::spawn(async move {
        let _ = connection.await;
    });
    admin
        .batch_execute(&format!("DROP SCHEMA {name} CASCADE"))
        .await
        .unwrap();
}
